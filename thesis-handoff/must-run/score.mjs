/**
 * Turns the results of a runtime check of "must" navigation edges into LaTeX macros.
 * Usage: node score.mjs --results <dir> --apps realworld,mifos --tex <out.tex>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HEADER = "% Generated by must-run/score.mjs from must-run/results. Do not edit.";

const OUTCOMES = [
  ["confirmed", "Confirmed"],
  ["other-target", "OtherTarget"],
  ["no-navigation", "NoNavigation"],
  ["not-rendered", "NotRendered"],
  ["unreached", "Unreached"],
];

const MEASURES = [
  "Checks",
  "Edges",
  "Constructs",
  "Confirmed",
  "OtherTarget",
  "NoNavigation",
  "NotRendered",
  "Unreached",
  "Triggered",
  "Share",
];

/**
 * Prints a message to stderr and exits with status 2.
 * @param {string} message
 * @returns {never}
 */
function fail(message) {
  process.stderr.write(`score.mjs: ${message}\n`);
  process.exit(2);
}

/**
 * Parses the command line into the results directory, app names and output path.
 * @param {string[]} argv
 * @returns {{results: string, apps: string[], tex: string}}
 */
function parseArgs(argv) {
  const values = {};
  for (let i = 0; i < argv.length; i += 2) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (!["--results", "--apps", "--tex"].includes(flag)) {
      fail(`unknown argument: ${flag}`);
    }
    if (value === undefined || value.startsWith("--")) {
      fail(`missing value for ${flag}`);
    }
    values[flag.slice(2)] = value;
  }
  if (!values.results || !values.apps || !values.tex) {
    fail("usage: node score.mjs --results <dir> --apps realworld,mifos --tex <out.tex>");
  }
  const apps = values.apps.split(",").map((name) => name.trim()).filter(Boolean);
  if (apps.length === 0) {
    fail("--apps must name at least one application");
  }
  for (const app of apps) {
    if (!/^[A-Za-z]+$/.test(app)) {
      fail(`application name must be letters only: ${app}`);
    }
  }
  return { results: values.results, apps, tex: values.tex };
}

/**
 * Reads and parses the results file of one application, exiting with status 2 when unusable.
 * @param {string} dir
 * @param {string} app
 * @returns {{edges: object[], counts: object}}
 */
function loadApp(dir, app) {
  const file = join(dir, `${app}.json`);
  let data;
  try {
    data = JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    fail(`cannot read ${file}: ${error.message}`);
  }
  if (!data || !Array.isArray(data.edges) || typeof data.counts !== "object" || data.counts === null) {
    fail(`${file} does not have the expected shape`);
  }
  return data;
}

/**
 * Recomputes the raw measures of one application from its edges and verifies the stored counts.
 * @param {string} app
 * @param {{edges: object[], counts: object}} data
 * @returns {Record<string, number>}
 */
function scoreApp(app, data) {
  const tally = Object.fromEntries(OUTCOMES.map(([key]) => [key, 0]));
  const sites = new Set();
  const edgeKeys = new Set();
  for (const edge of data.edges) {
    if (!Object.hasOwn(tally, edge.outcome)) {
      throw new Error(`${app}: edge ${edge.id} has unknown outcome ${edge.outcome}`);
    }
    tally[edge.outcome] += 1;
    sites.add(edge.site);
    edgeKeys.add(`${edge.from}->${edge.to}`);
  }
  for (const [key] of OUTCOMES) {
    if (data.counts[key] !== tally[key]) {
      throw new Error(`${app}: stored count ${key}=${data.counts[key]} differs from recomputed ${tally[key]}`);
    }
  }
  const raw = {
    Checks: data.edges.length,
    Edges: edgeKeys.size,
    Constructs: sites.size,
  };
  for (const [key, name] of OUTCOMES) {
    raw[name] = tally[key];
  }
  return raw;
}

/**
 * Adds the derived measures Triggered and Share to a set of raw measures.
 * @param {Record<string, number>} raw
 * @returns {Record<string, number|null>}
 */
function finalize(raw) {
  const triggered = raw.Confirmed + raw.OtherTarget + raw.NoNavigation;
  return {
    ...raw,
    Triggered: triggered,
    Share: triggered === 0 ? null : raw.Confirmed / triggered,
  };
}

/**
 * Sums raw per-application measures into pooled totals.
 * @param {Record<string, number>[]} raws
 * @returns {Record<string, number>}
 */
function pool(raws) {
  const total = {};
  for (const raw of raws) {
    for (const [name, value] of Object.entries(raw)) {
      total[name] = (total[name] ?? 0) + value;
    }
  }
  return total;
}

/**
 * Formats a share as a LaTeX percentage with one decimal, or "--" when undefined.
 * @param {number|null} share
 * @returns {string}
 */
function texShare(share) {
  return share === null ? "--" : `${(share * 100).toFixed(1)}\\,\\%`;
}

/**
 * Formats a share as a plain percentage with one decimal for terminal output.
 * @param {number|null} share
 * @returns {string}
 */
function plainShare(share) {
  return share === null ? "--" : `${(share * 100).toFixed(1)}%`;
}

/**
 * Upper-cases the first letter of a name.
 * @param {string} name
 * @returns {string}
 */
function capitalise(name) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/**
 * Builds the \newcommand lines for one labelled record.
 * @param {string} label
 * @param {Record<string, number|null>} record
 * @returns {string[]}
 */
function texLines(label, record) {
  return MEASURES.map((measure) => {
    const value = measure === "Share" ? texShare(record.Share) : String(record[measure]);
    return `\\newcommand{\\MustRun${label}${measure}}{${value}}`;
  });
}

/**
 * Builds the one-line stdout summary of a labelled record.
 * @param {string} label
 * @param {Record<string, number|null>} record
 * @returns {string}
 */
function summaryLine(label, record) {
  const parts = MEASURES.map((measure) => {
    const value = measure === "Share" ? plainShare(record.Share) : record[measure];
    return `${measure}=${value}`;
  });
  return `${label}: ${parts.join(" ")}`;
}

/**
 * Runs the scoring over all requested applications and writes the macro file.
 * @param {string[]} argv
 * @returns {void}
 */
function main(argv) {
  const { results, apps, tex } = parseArgs(argv);
  const entries = apps.map((app) => {
    const raw = scoreApp(app, loadApp(results, app));
    return { label: capitalise(app), raw };
  });
  // Distinct edges and constructs are counted per application so identical routes in different apps stay separate.
  entries.push({ label: "All", raw: pool(entries.map((entry) => entry.raw)) });

  const lines = [HEADER];
  for (const { label, raw } of entries) {
    const record = finalize(raw);
    lines.push(...texLines(label, record));
    process.stdout.write(`${summaryLine(label, record)}\n`);
  }
  try {
    writeFileSync(tex, `${lines.join("\n")}\n`);
  } catch (error) {
    fail(`cannot write ${tex}: ${error.message}`);
  }
}

main(process.argv.slice(2));
