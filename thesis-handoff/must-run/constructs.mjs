/**
 * Counts, across several driver result files, the distinct must constructs that were clicked and
 * landed on their target at least once, and writes the count as one LaTeX macro. The per-run
 * macros of score.mjs count checks; this is the construct-level total over all runs together.
 *
 * Usage: node constructs.mjs --tex <out.tex> <results.json> [<results.json> ...]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

/** The distinct app:site keys of the constructs with at least one confirmed check. */
export function confirmedConstructs(runs) {
  const keys = new Set()
  for (const { app, edges } of runs) {
    for (const e of edges) if (e.outcome === 'confirmed') keys.add(`${app}:${e.site}`)
  }
  return keys
}

/** The app:id keys of the checks that failed: landed elsewhere, did not navigate or were not rendered. */
export function failedChecks(runs) {
  const failed = ['other-target', 'no-navigation', 'not-rendered']
  return runs.flatMap(({ app, edges }) => edges.filter((e) => failed.includes(e.outcome)).map((e) => `${app}:${e.id}`))
}

/**
 * Reads the result files named on the command line and writes the macro file. The thesis states in
 * prose that no check failed, so any failed check stops the regeneration instead of going stale.
 */
function main(argv) {
  const i = argv.indexOf('--tex')
  if (i < 0 || !argv[i + 1]) throw new Error('usage: node constructs.mjs --tex <out.tex> <results.json> ...')
  const tex = argv[i + 1]
  const files = argv.filter((_, j) => j !== i && j !== i + 1)
  const runs = files.map((f) => ({ app: f.split('/').pop().replace(/\.json$/, ''), edges: JSON.parse(readFileSync(f, 'utf8')).edges }))
  const failed = failedChecks(runs)
  if (failed.length > 0) throw new Error(`failed checks contradict the thesis prose: ${failed.join(', ')}`)
  const n = confirmedConstructs(runs).size
  writeFileSync(tex, `% Generated by must-run/constructs.mjs from ${files.join(', ')}. Do not edit.\n\\newcommand{\\MustRunConfirmedConstructs}{${n}}\n`)
  console.log(`confirmed constructs: ${n}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
