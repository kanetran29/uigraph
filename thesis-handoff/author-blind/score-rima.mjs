/**
 * Compares the author's blind answers on rima-sheet.json with the source readings of the first
 * comparison with Rima et al. (rima/adjudication.json) and writes the counts as LaTeX macros plus
 * the disagreements with the author's reasons. Expected answers: a miss of class e (the reference
 * entry is wrong) spurious, a miss of any other class real; an extra pair its verdict; a pair no
 * reading judged (a constructed decoy) spurious. Run only after rima-verdicts.json is committed
 * (PROTOCOL.md); it refuses while any item is unanswered.
 *
 * Usage: node score-rima.mjs --tex <out.tex> [--out rima-comparison.json]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const KINDS = ['miss', 'real', 'spurious', 'decoy']

/** The item's kind and the answer that agrees with the reading behind it. */
export function expected(r) {
  if (!r) return { kind: 'decoy', answer: 'spurious' }
  if (r.kind === 'miss') return { kind: 'miss', answer: r.verdict === 'e' ? 'spurious' : 'real' }
  return { kind: r.verdict, answer: r.verdict }
}

/** Tallies agreement per kind of item: misses, extras judged real, extras judged spurious, decoys. */
export function compare(items, verdicts, adjudication) {
  const byPair = new Map(adjudication.map((x) => [`${x.slug} ${x.from} ${x.to}`, x]))
  const rows = items.map((it) => {
    const { kind, answer } = expected(byPair.get(`${it.app} ${it.from} ${it.to}`))
    const v = verdicts[it.id]
    return { id: it.id, app: it.app, from: it.from, to: it.to, kind, expected: answer, reader: v?.verdict ?? 'unanswered', reason: v?.reason ?? '' }
  })
  const tally = (kind) => {
    const rs = rows.filter((r) => r.kind === kind)
    return {
      items: rs.length,
      agree: rs.filter((r) => r.reader === r.expected).length,
      disagree: rs.filter((r) => r.reader !== r.expected && (r.reader === 'real' || r.reader === 'spurious')).length,
      undecided: rs.filter((r) => r.reader === 'unclear').length,
      unanswered: rs.filter((r) => r.reader === 'unanswered').length,
    }
  }
  return { rows, ...Object.fromEntries(KINDS.map((k) => [k, tally(k)])) }
}

/** Reads the sheet, the answers and the readings, and writes the macros and the comparison. */
function main(argv) {
  const arg = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : null)
  const here = (f) => new URL(f, import.meta.url)
  const { items } = JSON.parse(readFileSync(here('rima-sheet.json'), 'utf8'))
  const { verdicts } = JSON.parse(readFileSync(here('rima-verdicts.json'), 'utf8'))
  const result = compare(items, verdicts, JSON.parse(readFileSync(here('../rima/adjudication.json'), 'utf8')))
  const missing = KINDS.reduce((n, k) => n + result[k].unanswered, 0)
  if (missing > 0) throw new Error(`${missing} items unanswered; finish the sheet before scoring`)
  const name = (s) => s.charAt(0).toUpperCase() + s.slice(1)
  const m = (k, v) => `\\newcommand{\\AuthorRima${k}}{${v}}`
  const lines = ['% Generated by author-blind/score-rima.mjs from rima-verdicts.json. Do not edit.', m('Items', items.length)]
  for (const k of KINDS) for (const f of ['items', 'agree', 'disagree', 'undecided']) lines.push(m(name(k) + name(f), result[k][f]))
  writeFileSync(arg('tex'), lines.join('\n') + '\n')
  const tallies = Object.fromEntries(KINDS.map((k) => [k, result[k]]))
  writeFileSync(arg('out') ?? here('rima-comparison.json'), JSON.stringify({ ...tallies, disagreements: result.rows.filter((r) => r.reader !== r.expected) }, null, 1) + '\n')
  console.log(JSON.stringify(tallies))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
