/**
 * Compares the author's blind must-sheet answers with the extractor's final tier and writes the
 * counts as LaTeX macros plus a list of disagreements with the author's reasons. An item is must
 * for the extractor when route-oracle/results-must/tier-reading.json lists its construct, may
 * otherwise (the decoys). The reader's tier is must when both answers are yes, may when either is
 * no, undecided otherwise. Run only after the verdict file is committed (PROTOCOL.md).
 *
 * Usage: node score-must.mjs --tex <out.tex> [--out must-comparison.json]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

/** The reader's tier from the two answers: must, may or undecided. */
export function readerTier(v) {
  if (!v) return 'unanswered'
  if (v.target === 'no' || v.always === 'no') return 'may'
  if (v.target === 'yes' && v.always === 'yes') return 'must'
  return 'undecided'
}

/** Tallies agreement per kind of item (must constructs, may-only decoys). */
export function compare(items, verdicts, mustSites) {
  const rows = items.map((it) => {
    const extractor = mustSites.has(`${it.app}:${it.file}:${it.line}`) ? 'must' : 'may'
    const reader = readerTier(verdicts[it.id])
    return { id: it.id, app: it.app, site: `${it.file}:${it.line}`, extractor, reader, reason: verdicts[it.id]?.reason ?? '' }
  })
  const tally = (kind) => {
    const rs = rows.filter((r) => r.extractor === kind)
    return {
      items: rs.length,
      agree: rs.filter((r) => r.reader === kind).length,
      disagree: rs.filter((r) => r.reader !== kind && (r.reader === 'must' || r.reader === 'may')).length,
      undecided: rs.filter((r) => r.reader === 'undecided').length,
      unanswered: rs.filter((r) => r.reader === 'unanswered').length,
    }
  }
  return { rows, must: tally('must'), decoy: tally('may') }
}

/** Reads the sheet, the answers and the tier reading, and writes the macros and the comparison. */
function main(argv) {
  const arg = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : null)
  const here = (f) => new URL(f, import.meta.url)
  const { items } = JSON.parse(readFileSync(here('must-sheet.json'), 'utf8'))
  const { verdicts } = JSON.parse(readFileSync(here('must-verdicts.json'), 'utf8'))
  const tier = JSON.parse(readFileSync(here('../route-oracle/results-must/tier-reading.json'), 'utf8')).sites
  const result = compare(items, verdicts, new Set(tier.map((s) => `${s.app}:${s.site}`)))
  const missing = result.must.unanswered + result.decoy.unanswered
  if (missing > 0) throw new Error(`${missing} items unanswered; finish the sheet before scoring`)
  const m = (name, v) => `\\newcommand{\\AuthorMust${name}}{${v}}`
  const lines = ['% Generated by author-blind/score-must.mjs from must-verdicts.json. Do not edit.',
    m('Items', items.length), m('MustItems', result.must.items), m('DecoyItems', result.decoy.items),
    m('MustAgree', result.must.agree), m('MustDisagree', result.must.disagree), m('MustUndecided', result.must.undecided),
    m('DecoyAgree', result.decoy.agree), m('DecoyDisagree', result.decoy.disagree), m('DecoyUndecided', result.decoy.undecided)]
  writeFileSync(arg('tex'), lines.join('\n') + '\n')
  writeFileSync(arg('out') ?? here('must-comparison.json'), JSON.stringify({ must: result.must, decoy: result.decoy, disagreements: result.rows.filter((r) => r.reader !== r.extractor) }, null, 1) + '\n')
  console.log(JSON.stringify({ must: result.must, decoy: result.decoy }))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
