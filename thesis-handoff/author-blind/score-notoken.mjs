/**
 * Compares the author's blind answers on notoken-sheet.json with the head-to-head readings
 * (rima/head2head/results-v3/score.json) and writes the counts as LaTeX macros plus the
 * disagreements with the author's reasons. The reader's verdict is real when both answers are yes
 * (the trigger lands on the target and is shown on the start screen), spurious when either is no,
 * undecided otherwise. Items whose pair the author re-read with the verdict visible (tier 1 of
 * rima/STUDENT-READING.md, author-check.json) are counted as seen. Run only after
 * notoken-verdicts.json is committed (PROTOCOL.md); it refuses while any item is unanswered.
 *
 * Usage: node score-notoken.mjs --tex <out.tex> [--out notoken-comparison.json]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const KINDS = ['real', 'decoy']

/** The reader's verdict from the two answers: real, spurious or undecided. */
export function readerVerdict(v) {
  if (!v) return 'unanswered'
  if (v.target === 'no' || v.shown === 'no') return 'spurious'
  if (v.target === 'yes' && v.shown === 'yes') return 'real'
  return 'undecided'
}

/** The pairs listed in tier 1 of STUDENT-READING.md, as "slug from to". */
export function tier1(md) {
  const section = md.split(/^## /m).find((s) => s.startsWith('Tier 1')) ?? ''
  return new Set([...section.matchAll(/^\d+\. \[ \] \*\*(\S+)\*\* `([^`]+)` → `([^`]+)`/gm)].map((m) => `${m[1]} ${m[2]} ${m[3]}`))
}

/** Tallies agreement for the real pairs and for the decoys, counting the items seen before. */
export function compare(items, verdicts, read, seen) {
  const byPair = new Map(read.map((x) => [`${x.slug} ${x.from} ${x.to}`, x]))
  const rows = items.map((it) => {
    const k = `${it.app} ${it.from} ${it.to}`
    const kind = byPair.get(k).verdict === 'real' ? 'real' : 'decoy'
    return { id: it.id, app: it.app, from: it.from, to: it.to, site: `${it.file}:${it.line}`, kind, expected: kind === 'real' ? 'real' : 'spurious', reader: readerVerdict(verdicts[it.id]), seen: seen.has(k), reason: verdicts[it.id]?.reason ?? '' }
  })
  const tally = (kind) => {
    const rs = rows.filter((r) => r.kind === kind)
    return {
      items: rs.length,
      agree: rs.filter((r) => r.reader === r.expected).length,
      disagree: rs.filter((r) => r.reader !== r.expected && (r.reader === 'real' || r.reader === 'spurious')).length,
      undecided: rs.filter((r) => r.reader === 'undecided').length,
      unanswered: rs.filter((r) => r.reader === 'unanswered').length,
      seen: rs.filter((r) => r.seen).length,
      seenAgree: rs.filter((r) => r.seen && r.reader === r.expected).length,
    }
  }
  return { rows, real: tally('real'), decoy: tally('decoy') }
}

/** Reads the sheet, the answers and the readings, and writes the macros and the comparison. */
function main(argv) {
  const arg = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : null)
  const here = (f) => new URL(f, import.meta.url)
  const { items } = JSON.parse(readFileSync(here('notoken-sheet.json'), 'utf8'))
  const { verdicts } = JSON.parse(readFileSync(here('notoken-verdicts.json'), 'utf8'))
  const read = JSON.parse(readFileSync(here('../rima/head2head/results-v3/score.json'), 'utf8')).verdicts
  const result = compare(items, verdicts, read, tier1(readFileSync(here('../rima/STUDENT-READING.md'), 'utf8')))
  const missing = result.real.unanswered + result.decoy.unanswered
  if (missing > 0) throw new Error(`${missing} items unanswered; finish the sheet before scoring`)
  const name = (s) => s.charAt(0).toUpperCase() + s.slice(1)
  const m = (k, v) => `\\newcommand{\\AuthorNoToken${k}}{${v}}`
  const lines = ['% Generated by author-blind/score-notoken.mjs from notoken-verdicts.json. Do not edit.', m('Items', items.length)]
  for (const k of KINDS) for (const f of ['items', 'agree', 'disagree', 'undecided', 'seen', 'seenAgree']) lines.push(m(name(k) + name(f), result[k][f]))
  writeFileSync(arg('tex'), lines.join('\n') + '\n')
  writeFileSync(arg('out') ?? here('notoken-comparison.json'), JSON.stringify({ real: result.real, decoy: result.decoy, disagreements: result.rows.filter((r) => r.reader !== r.expected) }, null, 1) + '\n')
  console.log(JSON.stringify({ real: result.real, decoy: result.decoy }))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
