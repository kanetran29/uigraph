/**
 * Compares the author's blind answers on alfresco-sheet.json with the alfresco structural reference
 * (route-oracle/ground-truth/alfresco.json) and writes the counts as LaTeX macros plus each site the
 * two disagree on, with the author's reason. Per (site, screen) pair: in both, only in the reference
 * (the reader's set is smaller), only ticked by the reader (larger); per site: identical sets and
 * sites the reader marked unsure. Shell sites (reference screens ALL) are also counted apart. Run
 * only after alfresco-verdicts.json is committed (PROTOCOL.md); it refuses while any item lacks
 * the sure/unsure answer.
 *
 * Usage: node score-alfresco.mjs --tex <out.tex> [--out alfresco-comparison.json]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const FIELDS = ['sites', 'refPairs', 'agree', 'refOnly', 'readerOnly', 'exact', 'unsure']

/** Compares each site's reference screens with the screens the reader ticked. */
export function compare(items, verdicts, truth) {
  const ref = new Map(truth.sites.map((s) => [s.site, s.screens]))
  const rows = items.map((it) => {
    const site = `${it.file}:${it.line}`
    const r = ref.get(site)
    const want = new Set(r === 'ALL' ? truth.screens : r)
    const v = verdicts[it.id]
    const got = new Set(v?.screens ?? [])
    return { id: it.id, site, shell: r === 'ALL', want, got, sure: v?.sure ?? null, reason: v?.reason ?? '' }
  })
  const tally = (rs) => ({
    sites: rs.length,
    refPairs: rs.reduce((n, r) => n + r.want.size, 0),
    agree: rs.reduce((n, r) => n + [...r.want].filter((s) => r.got.has(s)).length, 0),
    refOnly: rs.reduce((n, r) => n + [...r.want].filter((s) => !r.got.has(s)).length, 0),
    readerOnly: rs.reduce((n, r) => n + [...r.got].filter((s) => !r.want.has(s)).length, 0),
    exact: rs.filter((r) => r.want.size === r.got.size && [...r.want].every((s) => r.got.has(s))).length,
    unsure: rs.filter((r) => r.sure === 'unsure').length,
    unanswered: rs.filter((r) => r.sure !== 'sure' && r.sure !== 'unsure').length,
  })
  return {
    all: tally(rows),
    nonShell: tally(rows.filter((r) => !r.shell)),
    rows: rows.map((r) => ({ id: r.id, site: r.site, shell: r.shell, refOnly: [...r.want].filter((s) => !r.got.has(s)), readerOnly: [...r.got].filter((s) => !r.want.has(s)), sure: r.sure, reason: r.reason })),
  }
}

/** Reads the sheet, the answers and the reference, and writes the macros and the comparison. */
function main(argv) {
  const arg = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : null)
  const here = (f) => new URL(f, import.meta.url)
  const { items } = JSON.parse(readFileSync(here('alfresco-sheet.json'), 'utf8'))
  const { verdicts } = JSON.parse(readFileSync(here('alfresco-verdicts.json'), 'utf8'))
  const result = compare(items, verdicts, JSON.parse(readFileSync(here('../route-oracle/ground-truth/alfresco.json'), 'utf8')))
  if (result.all.unanswered > 0) throw new Error(`${result.all.unanswered} items unanswered; finish the sheet before scoring`)
  const name = (s) => s.charAt(0).toUpperCase() + s.slice(1)
  const m = (k, v) => `\\newcommand{\\AuthorAlf${k}}{${v}}`
  const lines = ['% Generated by author-blind/score-alfresco.mjs from alfresco-verdicts.json. Do not edit.']
  for (const f of FIELDS) lines.push(m(name(f), result.all[f]), m('NonShell' + name(f), result.nonShell[f]))
  writeFileSync(arg('tex'), lines.join('\n') + '\n')
  const differ = result.rows.filter((r) => r.refOnly.length || r.readerOnly.length || r.sure === 'unsure')
  writeFileSync(arg('out') ?? here('alfresco-comparison.json'), JSON.stringify({ all: result.all, nonShell: result.nonShell, differ }, null, 1) + '\n')
  console.log(JSON.stringify({ all: result.all, nonShell: result.nonShell }))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
