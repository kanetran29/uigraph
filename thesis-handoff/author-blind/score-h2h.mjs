/**
 * Compares the author's blind answers on h2h-sheet.json with the head-to-head source readings
 * (rima/head2head/results-v3/score.json) and writes the counts as LaTeX macros plus the
 * disagreements with the author's reasons. Groups: the mifos sample and the pairs on Rima et al.'s
 * subjects, each in all and split by the AI verdict (real, spurious). An answer agrees when it
 * equals the AI verdict; unclear on either side is undecided. Run only after h2h-verdicts.json is
 * committed (PROTOCOL.md); it refuses while any item is unanswered.
 *
 * Usage: node score-h2h.mjs --tex <out.tex> [--out h2h-comparison.json]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const GROUPS = ['mifos', 'rima']
const SPLITS = ['all', 'real', 'spurious']

/** Counts agreement over rows: decided both sides and equal, decided and different, undecided, unanswered. */
function tally(rs) {
  const decided = (v) => v === 'real' || v === 'spurious'
  return {
    items: rs.length,
    agree: rs.filter((r) => decided(r.ai) && r.reader === r.ai).length,
    disagree: rs.filter((r) => decided(r.ai) && decided(r.reader) && r.reader !== r.ai).length,
    undecided: rs.filter((r) => r.reader !== 'unanswered' && (!decided(r.ai) || !decided(r.reader))).length,
    unanswered: rs.filter((r) => r.reader === 'unanswered').length,
  }
}

/** Tallies the answers per group and per AI verdict. */
export function compare(items, verdicts, read) {
  const byPair = new Map(read.map((x) => [`${x.slug} ${x.from} ${x.to}`, x]))
  const rows = items.map((it) => {
    const v = verdicts[it.id]
    return { id: it.id, app: it.app, from: it.from, to: it.to, group: it.app === 'mifos' ? 'mifos' : 'rima', ai: byPair.get(`${it.app} ${it.from} ${it.to}`).verdict, reader: v?.verdict ?? 'unanswered', reason: v?.reason ?? '' }
  })
  const out = { rows }
  for (const g of GROUPS) {
    const rs = rows.filter((r) => r.group === g)
    out[g] = { all: tally(rs), real: tally(rs.filter((r) => r.ai === 'real')), spurious: tally(rs.filter((r) => r.ai === 'spurious')) }
  }
  return out
}

/** Reads the sheet, the answers and the readings, and writes the macros and the comparison. */
function main(argv) {
  const arg = (n) => (argv.includes(`--${n}`) ? argv[argv.indexOf(`--${n}`) + 1] : null)
  const here = (f) => new URL(f, import.meta.url)
  const { items } = JSON.parse(readFileSync(here('h2h-sheet.json'), 'utf8'))
  const { verdicts } = JSON.parse(readFileSync(here('h2h-verdicts.json'), 'utf8'))
  const result = compare(items, verdicts, JSON.parse(readFileSync(here('../rima/head2head/results-v3/score.json'), 'utf8')).verdicts)
  const missing = result.mifos.all.unanswered + result.rima.all.unanswered
  if (missing > 0) throw new Error(`${missing} items unanswered; finish the sheet before scoring`)
  const name = (s) => s.charAt(0).toUpperCase() + s.slice(1)
  const m = (k, v) => `\\newcommand{\\AuthorHH${k}}{${v}}`
  const lines = ['% Generated by author-blind/score-h2h.mjs from h2h-verdicts.json. Do not edit.', m('Items', items.length)]
  for (const g of GROUPS) for (const s of SPLITS) for (const f of ['items', 'agree', 'disagree', 'undecided']) lines.push(m(name(g) + (s === 'all' ? '' : name(s)) + name(f), result[g][s][f]))
  writeFileSync(arg('tex'), lines.join('\n') + '\n')
  const tallies = { mifos: result.mifos, rima: result.rima }
  writeFileSync(arg('out') ?? here('h2h-comparison.json'), JSON.stringify({ ...tallies, disagreements: result.rows.filter((r) => r.reader !== r.ai) }, null, 1) + '\n')
  console.log(JSON.stringify(tallies))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
