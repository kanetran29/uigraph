/**
 * Validity check V2 of PREREGISTRATION.txt, against this extractor's screens rather than the
 * independent parser's: for each application, how many route paths their tool records, how many of
 * those name a screen of ours by their text, how many of our route declarations their routes are
 * written at, out of how many, and how many screens ours has. Writes results/routes-v2.json and LaTeX macros.
 *
 * Usage: node routes-v2.mjs --work <work dir> --decls results/route-decls.json --json <out> --tex <out>
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { gunzipSync } from 'node:zlib'
import { DatabaseSync } from 'node:sqlite'
import { norm } from '../../e2e-nav/score.mjs'

const a = {}
for (let i = 2; i < process.argv.length; i += 2) a[process.argv[i].replace(/^--/, '')] = process.argv[i + 1]
const here = new URL('.', import.meta.url).pathname
const decls = JSON.parse(readFileSync(a.decls, 'utf8'))
const route = (r) => '/' + String(r).split('/').filter(Boolean).join('/')
const out = {}
let tex = '% Generated by rima/head2head/routes-v2.mjs. Do not edit.\n'
const tot = { theirs: 0, byPath: 0, declsHit: 0, decls: 0, ours: 0 }
for (const line of readFileSync(join(here, 'apps.txt'), 'utf8').split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue
  const [slug, dir] = line.split(/\s+/)
  const gz = join(here, '..', 'graphs-repaired', `${slug}.full.json.gz`)
  const g = existsSync(gz) ? JSON.parse(gunzipSync(readFileSync(gz)).toString()) : JSON.parse(new DatabaseSync(join(a.work, dir, 'uigraph.db')).prepare("select json from docs where key='graph'").get().json)
  const ours = new Set(g.nodes.filter((n) => n.kind === 'screen' && !/\*/.test(n.route)).map((n) => norm(route(n.route))))
  const theirs = JSON.parse(readFileSync(join(a.work, 'rima', 'theirs', slug, 'json', 'routes.json'), 'utf8')).routes.filter((r) => r.kind !== 'RedirectRoute' && !/\*/.test(r.fullPath))
  const paths = new Set(theirs.map((r) => norm(route(r.fullPath))))
  const byPath = [...paths].filter((p) => ours.has(p)).length
  // Our route declarations their routes are written at (a declaration may be mounted at several paths).
  const declKeys = new Set(Object.keys(decls[slug] ?? {}))
  const hit = new Set(theirs.map((r) => `${r.origin?.file}:${r.origin?.startLine}`).filter((k) => declKeys.has(k)))
  out[slug] = { theirs: paths.size, byPath, declsHit: hit.size, decls: declKeys.size, ours: ours.size }
  for (const k of Object.keys(tot)) tot[k] += out[slug][k]
  const N = slug.replace(/\d/g, (d) => ['Zero', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine'][d]).split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('')
  for (const [k, v] of Object.entries(out[slug])) tex += `\\newcommand{\\HHRoutes${N}${k.charAt(0).toUpperCase() + k.slice(1)}}{${v}}\n`
  console.log(slug.padEnd(26), JSON.stringify(out[slug]))
}
for (const [k, v] of Object.entries(tot)) tex += `\\newcommand{\\HHRoutesAll${k.charAt(0).toUpperCase() + k.slice(1)}}{${v}}\n`
writeFileSync(a.json, JSON.stringify(out, null, 1) + '\n')
writeFileSync(a.tex, tex)
