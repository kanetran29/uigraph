/**
 * Writes the macros of the author's own check of the AI readings (results-v3/author-check.json).
 * Usage: node author-check.mjs <author-check.json> <out.tex>
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { wilson } from './score.mjs'

const [inp, out] = process.argv.slice(2)
const c = JSON.parse(readFileSync(inp, 'utf8'))
if (c.agree + c.disagree.length !== c.judged || c.judged > c.sample) throw new Error('author-check.json does not add up')
let tex = '% Generated by rima/head2head/author-check.mjs from results-v3/author-check.json. Do not edit.\n'
for (const [k, v] of Object.entries({ Sample: c.sample, Judged: c.judged, Agree: c.agree, Disagree: c.disagree.length })) tex += `\\newcommand{\\HHAuthor${k}}{${v}}\n`
const [lo, hi] = wilson(c.agree, c.judged)
const pct = (x) => `${(100 * x).toFixed(1)}\\,\\%`
tex += `\\newcommand{\\HHAuthorAgreeRange}{${pct(lo)}--${pct(hi)}}\n`
writeFileSync(out, tex)
console.log(tex)
