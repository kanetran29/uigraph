/**
 * The site check PREREGISTRATION.txt promises for the head-to-head readings, run after scoring: for
 * every pair whose final verdict is real, the cited file exists in the application's checkout and a
 * link, router call or event binding (the token list of ../check-sites.mjs) stands within two lines
 * of the cited line. A token match only: it does not test that the construct leads to the target.
 * Lists the failures. With --tex it writes the counts as macros and exits 0, since a site the token
 * list does not cover is not an error; without it, it exits 1 on any failure.
 *
 * Usage: node check-sites.mjs --score results-v3/score.json --apps apps.txt --work <work dir> [--tex <out.tex>]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const a = {}
for (let i = 2; i < process.argv.length; i += 2) a[process.argv[i].replace(/^--/, '')] = process.argv[i + 1]
const dirs = {}
for (const l of readFileSync(a.apps, 'utf8').split('\n')) {
  if (!l.trim() || l.startsWith('#')) continue
  const [slug, dir] = l.split(/\s+/)
  dirs[slug] = join(a.work, dir)
}
const nav = /routerLink|navigate|href|ngSubmit|\(click\)|\(submit\)|redirectTo|dispatch|emit|location/i
const bad = []
let checked = 0
for (const x of JSON.parse(readFileSync(a.score, 'utf8')).verdicts) {
  if (x.verdict !== 'real') continue
  checked++
  const m = /^(.+?):(\d+)/.exec(x.site ?? '')
  const file = m && join(dirs[x.slug], m[1])
  if (!m || !existsSync(file)) { bad.push(`${x.slug} ${x.from} -> ${x.to}: no file at ${x.site}`); continue }
  const n = Number(m[2])
  const lines = readFileSync(file, 'utf8').split('\n').slice(Math.max(0, n - 3), n + 2).join('\n')
  if (!nav.test(lines)) bad.push(`${x.slug} ${x.from} -> ${x.to}: no navigation near ${x.site}`)
}
console.log(`checked ${checked} cited sites, ${bad.length} failed`)
for (const b of bad) console.log('  ' + b)
if (a.tex) {
  writeFileSync(a.tex, '% Generated by rima/head2head/check-sites.mjs from results-v3/score.json. Do not edit.\n' +
    `\\newcommand{\\HHSitesToken}{${checked - bad.length}}\n\\newcommand{\\HHSitesNoToken}{${bad.length}}\n`)
} else process.exit(bad.length ? 1 : 0)
