#!/usr/bin/env node
//
// Counts the constructs that Section 6.3 declares as in scope or approximated, so that
// the prevalence table is reproducible instead of resting on an ad hoc grep.
//
// This is a call-site count over the application sources with tests excluded. It is NOT
// the construct denominator of Chapter 5: that comes from the route-oracle parser, which
// resolves bindings rather than matching text. The two therefore disagree, and the
// thesis reports only the approximated rows from here.
//
// usage: node approx-counts.mjs <slug>=<appDir> [<slug>=<appDir> ...] [--tex]
//
import fs from 'node:fs'
import path from 'node:path'

const PATTERNS = [
  ['routerLink',       /routerLink/,            'in scope'],
  ['router.navigate',  /router\.navigate\(/,    'in scope'],
  ['navigateByUrl',    /navigateByUrl\(/,       'in scope'],
  ['dialog.open',      /dialog\.open\(/,        'approximated'],
  ['auxiliary outlets', /\{\s*outlets\s*:/,     'approximated'],
  ['relativeTo',       /relativeTo/,            'approximated'],
  ['TemplateRef',      /TemplateRef/,           'approximated'],
  ['createEffect',     /createEffect\(/,        'approximated'],
]

const SKIP_DIR = new Set(['node_modules', 'dist', 'coverage'])
const isSource = (n) => /\.(ts|html)$/.test(n) && !/\.(spec|test)\.ts$/.test(n)

/** Every source line of the application, excluding tests and build output. */
function lines(dir) {
  const out = []
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      if (SKIP_DIR.has(e.name) || e.name.startsWith('.')) continue
      const p = path.join(d, e.name)
      if (e.isDirectory()) walk(p)
      else if (isSource(e.name)) out.push(...fs.readFileSync(p, 'utf8').split('\n'))
    }
  }
  walk(dir)
  return out
}

const apps = process.argv.slice(2).filter((a) => a.includes('=')).map((a) => {
  const [slug, dir] = a.split('=')
  return { slug, dir, lines: lines(path.resolve(dir)) }
})
const tex = process.argv.includes('--tex')

const counts = {}
for (const [name, re] of PATTERNS) {
  counts[name] = apps.map((a) => a.lines.filter((l) => re.test(l)).length)
}

if (!tex) {
  console.log(`construct          status        ${apps.map((a) => a.slug.padStart(12)).join('')}`)
  for (const [name, , status] of PATTERNS) {
    console.log(`${name.padEnd(19)}${status.padEnd(14)}${counts[name].map((n) => String(n).padStart(12)).join('')}`)
  }
} else {
  // Only the approximated rows are reported in the thesis; the in-scope rows are a
  // different unit from the Chapter 5 denominator and are left out on purpose.
  console.log('% Generated by approx-counts.mjs. Do not edit by hand.')
  console.log(`\\newcommand{\\TabApproxCounts}{%\n\\begin{tabular}{@{}l${'r'.repeat(apps.length)}@{}}`)
  console.log('\\toprule')
  console.log(`Construct & ${apps.map((a) => a.slug).join(' & ')} \\\\\n\\midrule`)
  for (const [name, , status] of PATTERNS) {
    if (status !== 'approximated') continue
    // code identifiers go in \texttt; a multi-word name is prose
    const label = name.includes(' ') ? name : `\\texttt{${name}}`
    console.log(`${label} & ${counts[name].join(' & ')} \\\\`)
  }
  console.log('\\bottomrule\n\\end{tabular}}')
}
