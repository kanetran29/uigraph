// The mutants of the demotion-rule sweep, as data: each deletes (or weakens) one rule or one term of
// a rule in a copy of packages/adapter-angular, and the sweep (mutation-sweep.mjs) runs the adapter's
// whole suite against each in turn. A mutant is {id, rule, file, find, replace}: `file` is under
// packages/adapter-angular/src, and `find` must occur exactly once in it. `find` and `replace` are
// arrays of equal length where a rule is deleted from two places at once. Ids 1 to 72 are the
// mutants of the one-off sweep recorded in results-must/mutation-sweep.json at a8c7480, with the
// find strings brought up to the adapter as it is now; 59a to 59c split mutant 59 and the
// controls-mode hole term; the rest delete each caller of the `capMay` cap, each logical-assignment
// token of the operator list, and each rule added since by the router fixes: matrix parameters and
// the preserved prefix, the identity of a wrapper call, redirect rivals and `pathMatch`, the
// routes the router tries (canMatch, canLoad), a `redirectTo` that is not a string, a title that is
// a resolver, and the guards of a route on a named outlet. Id 91 is retired: dropping the
// `t.relative === true` conjunct of the preserved-prefix computation changes nothing, since a target
// that is not relative resolves against the base '/', for which keptSegments returns 0 however
// many segments it climbs.

/**
 * Why a mutant list cannot be run against the sources `read` returns, as sentences; empty when it
 * can. Every `find` has to occur exactly once, because a mutant whose find is gone tests nothing
 * and one that occurs twice edits a site the author did not mean. Ids must be unique, and an edit
 * must change the source.
 */
export function mutationProblems(mutants, read) {
  const problems = []
  const seen = new Set()
  for (const m of mutants) {
    if (seen.has(m.id)) problems.push(`${m.id}: the id is used twice`)
    seen.add(m.id)
    const finds = [m.find].flat()
    const replaces = [m.replace].flat()
    if (finds.length !== replaces.length) problems.push(`${m.id}: ${finds.length} find string(s) and ${replaces.length} replacement(s)`)
    let src
    try {
      src = read(m.file)
    } catch {
      problems.push(`${m.id}: cannot read ${m.file}`)
      continue
    }
    finds.forEach((find, k) => {
      const count = find === '' ? 0 : src.split(find).length - 1
      if (count !== 1) problems.push(`${m.id} (${m.rule}): ${JSON.stringify(find.slice(0, 80))} occurs ${count} times in ${m.file}, not once`)
      if (find === replaces[k]) problems.push(`${m.id}: the replacement equals the find string`)
    })
  }
  return problems
}

/**
 * The source text with the mutant's edits applied. Each find is replaced once, by a function so
 * that a `$` in the replacement is not read as a pattern.
 */
export function applyMutant(m, src) {
  const finds = [m.find].flat()
  const replaces = [m.replace].flat()
  return finds.reduce((text, find, k) => text.replace(find, () => replaces[k]), src)
}

