// a rule in a copy of packages/adapter-angular, and the sweep (mutation-sweep.mjs) runs the adapter's
// whole suite against each in turn. A mutant is {id, rule, file, find, replace}: `file` is under
// packages/adapter-angular/src, and `find` must occur exactly once in it. `find` and `replace` are
// arrays of equal length where a rule is deleted from two places at once. Ids 1 to 72 are the
// mutants of the one-off sweep recorded in results-must/mutation-sweep.json at a8c7480, with the
// find strings brought up to the adapter as it is now; 59a to 59c split mutant 59 and the
// controls-mode hole term; the rest delete each caller of the `capMay` cap, each logical-assignment
// token of the operator list, and each rule added since by the router fixes: matrix parameters and
// the preserved prefix, the identity of a wrapper call, redirect rivals and `pathMatch`, the
// routes the router tries (canMatch, canLoad), a `redirectTo` that is not a string, a title that is
// a resolver, and the guards of a route on a named outlet. Ids 47a, 106a and 150 to 161 delete the
// rules of the second supersede reading (a later branch, member, service or module function, the
// enclosing blocks, a finally block, an awaited navigation), the per-placement firm-outlet test,
// the empty-path chain that renders on the screen above, and the conditional-outlet term of
// controls mode. Id 106 is retired with the redirect rework: a catch-all is now among the redirects
// the router may meet, in declaration order, and 106a deletes the term that limits the order
// assumption to catch-alls instead. Ids 162 to 164 delete the refusal of a relative target that
// climbs above the root. Id 128 is retired as equivalent: an empty-path child's unreadable redirect is also
// registered in the redirect table at the same address, which hides the screen and makes the
// address ambiguous whether or not the screen records it too. Id 110 is retired as equivalent: two distinct route levels share a parent
// only as elements of one array (a spread, a `children` call and a named constant each give its
// own parent), so `before` cannot tell the route-table check from its absence. Id 91 is retired: dropping the
// `t.relative === true` conjunct of the preserved-prefix computation changes nothing, since a target
// that is not relative resolves against the base '/', for which keptSegments returns 0 however
// many segments it climbs.
// The pure helpers the sweep (mutation-sweep.mjs) and the tests share sit beside the list: the
// checks that it applies (mutationProblems, unappliedIds), the edit (applyMutant), the reading of
// a run (judge) and the file the sweep writes (sweepRecord).

import { adapterSrcTree } from './provenance.mjs'

/**
 * Why a mutant list cannot be run against the sources `read` returns, as sentences; empty when it
 * can. Every `find` has to occur exactly once, because a mutant whose find is gone tests nothing
 * and one that occurs twice edits a site the author did not mean. Ids must be unique, and an edit
 * must change the source.
 */
export function mutationProblems(mutants, read) {
  const problems = []
  const seen = new Set()
  for (const m of mutants) {
    if (seen.has(m.id)) problems.push(`${m.id}: the id is used twice`)
    seen.add(m.id)
    const finds = [m.find].flat()
    const replaces = [m.replace].flat()
    if (finds.length !== replaces.length) problems.push(`${m.id}: ${finds.length} find string(s) and ${replaces.length} replacement(s)`)
    let src
    try {
      src = read(m.file)
    } catch {
      problems.push(`${m.id}: cannot read ${m.file}`)
      continue
    }
    finds.forEach((find, k) => {
      const count = find === '' ? 0 : src.split(find).length - 1
      if (count !== 1) problems.push(`${m.id} (${m.rule}): ${JSON.stringify(find.slice(0, 80))} occurs ${count} times in ${m.file}, not once`)
      if (find === replaces[k]) problems.push(`${m.id}: the replacement equals the find string`)
    })
  }
  return problems
}

/**
 * The ids of the mutants that cannot be applied to the sources `read` returns, in list order: the
 * ones whose find string is gone or occurs twice, or whose edit changes nothing. When the adapter
 * changes under the list, this is what names the mutants to bring up to it.
 */
export function unappliedIds(mutants, read) {
  return mutants.filter((m) => mutationProblems([m], read).length > 0).map((m) => m.id)
}

/**
 * What the suite said about one run of a mutant: the `Tests` summary line, whether it passed whole
 * (survived), and the name of the first test that failed. A run with no summary line (the suite did
 * not start, timed out or crashed) is not a kill by a test, so the mutant is counted as not killed:
 * it is listed with the survivors, sweep-to-latex.mjs refuses it, and its result says that the
 * suite did not run. `baselineTests` is the total the unmutated suite ran, which a run that passes
 * with a different total did not match.
 */
export function judge(output, baselineTests) {
  const lines = output.replace(/\x1b\[[0-9;]*m/g, '').split('\n').map((l) => l.trim())
  const summary = lines.find((l) => /^Tests\s/.test(l))
  const firstFail = lines.find((l) => /^FAIL\s/.test(l))
  if (!summary) return { result: 'no Tests line: the suite did not run', survived: true, killedBy: null }
  const survived = !/failed/.test(summary) && summary.includes(`(${baselineTests})`)
  return { result: summary, survived, killedBy: survived ? null : (firstFail ?? 'a test failed').replace(/^FAIL\s+/, '') }
}

/**
 * The file a sweep writes: the commit it ran at and the tree of packages/adapter-angular/src at
 * HEAD (`srcTree`, which sweep-to-latex.mjs holds against HEAD's later; the sweep refuses to run
 * on a dirty packages/, so HEAD's tree is the tree it ran on), the unmutated baseline and one entry
 * per mutant, marked partial when only some of the list was run.
 */
export function sweepRecord({ commit, baseline, partial, mutants }) {
  const srcTree = adapterSrcTree('HEAD')
  const survivors = mutants.filter((m) => m.survived)
  const note = `Each demotion rule the thesis lists deleted in turn from a copy of packages/adapter-angular at ${commit}, ` +
    `the full adapter suite run against it by mutation-sweep.mjs; a mutant survives when the suite still passes. ` +
    `${survivors.length} of ${mutants.length} survived or did not run.`
  return { note, commit, srcTree, baseline, ...(partial ? { partial: true } : {}), mutants }
}

/**
 * The source text with the mutant's edits applied. Each find is replaced once, by a function so
 * that a `$` in the replacement is not read as a pattern.
 */
export function applyMutant(m, src) {
  const finds = [m.find].flat()
  const replaces = [m.replace].flat()
  return finds.reduce((text, find, k) => text.replace(find, () => replaces[k]), src)
}

