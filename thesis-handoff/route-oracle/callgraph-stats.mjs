#!/usr/bin/env node
// How the member-level call graph resolved the calls it followed, per application.
//
// A call on a field is resolved through the field's declared type: to the class it names, through
// a provider binding, to the subclasses of an abstract class, or not at all when the type is an
// application class with neither. A type the application does not declare (the framework's, a
// library's) is not counted. The counts are what Section 6 quotes beside the binding approximation.
//
// Usage: pnpm exec tsx callgraph-stats.mjs --corpus <dir> --out <dir> [--tex <file>]
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { buildProject } from '../../packages/adapter-angular/src/extract.ts'
import { attributeScopes } from '../../packages/adapter-angular/src/attribute.ts'
import { collectRoutes } from '../../packages/adapter-angular/src/routes.ts'
import { extractorStamp } from './provenance.mjs'

const argv = process.argv.slice(2)
const flag = (n) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : undefined }
const corpus = flag('--corpus'), outDir = flag('--out'), tex = flag('--tex')
if (!corpus || !outDir) { console.error('usage: pnpm exec tsx callgraph-stats.mjs --corpus <dir> --out <dir> [--tex <file>]'); process.exit(2) }
const APPS = { realworld: '.', alfresco: 'projects/aca-content', ghostfolio: 'apps/client', k8sdash: 'modules/web', bitwarden: 'apps/web', mifos: '.' }

const rows = []
for (const [slug, sub] of Object.entries(APPS)) {
  const dir = path.resolve(corpus, slug, sub)
  const project = buildProject(dir)
  const scopes = attributeScopes(project.getSourceFiles(), collectRoutes(project, new Map(), undefined, dir), dir, 'full')
  rows.push({ slug, ...scopes.memberResolved })
}
const sum = (k) => rows.reduce((a, r) => a + r[k], 0)
mkdirSync(outDir, { recursive: true })
writeFileSync(path.join(outDir, 'callgraph-stats.json'), JSON.stringify({ rows }, null, 2) + '\n')
if (tex) {
  writeFileSync(tex, ['% Generated by callgraph-stats.mjs. Do not edit by hand.', extractorStamp(),
    `\\newcommand{\\CGDirect}{${sum('direct')}}`, `\\newcommand{\\CGBound}{${sum('bound')}}`,
    `\\newcommand{\\CGSubclass}{${sum('subclass')}}`, `\\newcommand{\\CGUnresolved}{${sum('unresolved')}}`,
    `\\newcommand{\\CGUnresolvedApps}{${rows.filter((r) => r.unresolved > 0).length}}`].join('\n') + '\n')
}
console.log(JSON.stringify(rows))
