#!/usr/bin/env node
//
// Audits the nodes the differential test cannot match to a declared screen, which
// Section 5.1 reports as a count and this script decomposes. It answers the question the
// count alone leaves open: is an unmatched node a defect of the extractor, a limit of the
// oracle, or a node the model's screen set does not admit?
//
// It reuses the parser's own path normalisation and classifies each unmatched node by the
// kinds of route the parser found at that path. A node whose path holds only a PREFIX or a
// REDIRECT route is outside S, which Chapter 3 defines over component-bearing routes only.
//
// usage: node node-audit.mjs <results-dir> [--tex]
//
import fs from 'node:fs'
import path from 'node:path'

const dir = process.argv[2]
const tex = process.argv.includes('--tex')
const SLUGS = ['realworld', 'alfresco', 'ghostfolio', 'k8sdash', 'bitwarden', 'mifos']
const NAME = { realworld: 'realworld', alfresco: 'alfresco', ghostfolio: 'ghostfolio', k8sdash: 'k8s dashboard', bitwarden: 'bitwarden', mifos: 'mifos' }

/** The parser's normalisation, copied so the audit joins on exactly the same key. */
const norm = (p) => (p || '').replace(/\/+$/, '').replace(/^\/?/, '/') || '/'

const CATS = [
  ['noRoute', 'No route declared at that path'],
  ['blind', 'Parser could not follow the route'],
  ['outsideS', 'Route is a prefix or a redirect, so outside $S$'],
  ['screen', 'Declared screen, so a join artefact'],
]

const per = {}
for (const slug of SLUGS) {
  const p = path.join(dir, 'raw', `${slug}.C.json`)
  if (!fs.existsSync(p)) continue
  const j = JSON.parse(fs.readFileSync(p, 'utf8'))
  const byPath = new Map()
  for (const r of j.routes) {
    const k = norm(r.path)
    if (!byPath.has(k)) byPath.set(k, new Set())
    byPath.get(k).add(r.kind)
  }
  const c = { noRoute: 0, blind: 0, outsideS: 0, screen: 0, total: 0 }
  for (const e of j.comparison.extraNodes) {
    c.total++
    const kinds = byPath.get(norm(e.route))
    if (!kinds) c.noRoute++
    else if ([...kinds].every((k) => k === 'PREFIX' || k === 'REDIRECT')) c.outsideS++
    // Both kinds are a route the oracle knows is there and cannot address: a lazy module it
    // could not open, or a path expression it could not read. An extra node at such a path is
    // the oracle's blind spot, not a node answering to nothing.
    else if (kinds.has('LAZY_UNRESOLVED') || kinds.has('SCREEN_UNRESOLVED')) c.blind++
    else if (kinds.has('SCREEN')) c.screen++
    else c.noRoute++
  }
  per[slug] = c
}

const sum = (k) => Object.values(per).reduce((a, c) => a + c[k], 0)

if (!tex) {
  console.log(`  ${'app'.padEnd(13)}${'extra'.padStart(6)}${'noRoute'.padStart(9)}${'blind'.padStart(7)}${'outsideS'.padStart(10)}${'screen'.padStart(8)}`)
  for (const [s, c] of Object.entries(per))
    console.log(`  ${s.padEnd(13)}${String(c.total).padStart(6)}${String(c.noRoute).padStart(9)}${String(c.blind).padStart(7)}${String(c.outsideS).padStart(10)}${String(c.screen).padStart(8)}`)
  console.log(`  ${'ALL'.padEnd(13)}${String(sum('total')).padStart(6)}${String(sum('noRoute')).padStart(9)}${String(sum('blind')).padStart(7)}${String(sum('outsideS')).padStart(10)}${String(sum('screen')).padStart(8)}`)
} else {
  const slugs = Object.keys(per)
  let out = '% Generated by node-audit.mjs. Do not edit by hand.\n'
  out += `\\newcommand{\\TabNodeAudit}{%\n\\begin{tabular}{@{}l${'r'.repeat(slugs.length)}r@{}}\n\\toprule\n`
  out += `Why the node has no declared screen & ${slugs.map((s) => ({ realworld: 'rw', alfresco: 'alf', ghostfolio: 'gf', k8sdash: 'k8s', bitwarden: 'bw', mifos: 'mif' })[s]).join(' & ')} & Total \\\\\n\\midrule\n`
  for (const [k, label] of CATS) {
    const v = slugs.map((s) => per[s][k])
    out += `${label} & ${v.join(' & ')} & ${v.reduce((a, b) => a + b, 0)} \\\\\n`
  }
  out += `\\midrule\nUnmatched nodes & ${slugs.map((s) => per[s].total).join(' & ')} & ${sum('total')} \\\\\n`
  out += `\\bottomrule\n\\end{tabular}}\n`
  process.stdout.write(out)
}
