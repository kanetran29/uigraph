#!/usr/bin/env node
// The figures the thesis cites for the instrument this evaluation began with.
//
// Chapters 5, 6 and 7 compare the current must tier and the current recovery source against
// the state of the extractor before the re-measurement, in order to say what the corrections
// cost and what they bought. Those figures cannot be re-measured: the extractor has moved,
// and running it now would measure a different tool. What is durable is the generated result
// files as they stood at that commit, so this script reads the figures out of git instead of
// letting the chapters quote them by hand -- which is how they were quoted until now, and the
// only numbers in the thesis that no file in the working tree accounted for.
//
// Usage: node earlier-instrument.mjs [--commit <sha>] [--tex <file>]
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const argv = process.argv.slice(2)
const flag = (n, d) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : d }
// The last commit before the re-measurement, so the figures are the ones the chapters
// describe as the state the work began with rather than an intermediate one.
const commit = flag('--commit', 'f17a302')
const THESIS = 'thesis-handoff/thesis'
const repo = path.resolve(path.join(import.meta.dirname, '..', '..'))

/** A generated .tex file as it stood at the named commit. */
const at = (file) =>
  execFileSync('git', ['show', `${commit}:${THESIS}/${file}`], { cwd: repo, encoding: 'utf8' })

const macro = (text, name) => {
  const m = text.match(new RegExp(`\\\\newcommand\\{\\\\${name}\\}\\{([^}]*)\\}`))
  if (!m) throw new Error(`${name} is not defined at ${commit}, so the chapters cannot cite it`)
  return m[1]
}

const round2 = at('generated-round2.tex')
const [clean, edges] = macro(round2, 'RoundTwoMustClean').split('/').map(Number)
const violations = Number(macro(round2, 'RoundTwoMustViolations'))
if (clean + violations !== edges) {
  throw new Error(`${clean} clean and ${violations} violations do not account for ${edges} edges at ${commit}`)
}

// The must column of the recovery-source table: what the gain in deterministic transitions
// came out of, by the class the loss rules had assigned the construct to.
const recovery = at('generated-before-after.tex')
const row = (label) => {
  const m = recovery.match(new RegExp(`${label} & (\\d+) & (\\d+) & (\\d+) \\\\\\\\`))
  if (!m) throw new Error(`the recovery-source table at ${commit} has no "${label}" row`)
  return { must: Number(m[1]), may: Number(m[2]), total: Number(m[3]) }
}
const fromAttribution = row('Out of the attribution classes')
const fromNode = row('Out of the node classes')
const allGained = row('All conversions gained')
if (fromAttribution.must + fromNode.must !== allGained.must) {
  throw new Error(`the must column at ${commit} does not sum: ` +
    `${fromAttribution.must} + ${fromNode.must} != ${allGained.must}`)
}

// How much larger that tier was than the one the thesis publishes, read from the current
// generated file so the factor cannot drift away from the figure beside it.
const nowEdges = Number(macro(readFileSync(path.join(repo, THESIS, 'generated-round2.tex'), 'utf8'), 'RoundTwoMustEdges'))
const share = (n, d) => {
  const v = (n / d) * 100
  if (!Number.isFinite(v) || v < 0 || v > 100) throw new Error(`${v} is not a share`)
  return `${v.toFixed(1)}\\,\\%`
}

let out = `% Generated by earlier-instrument.mjs from the result files at ${commit}. Do not edit by hand.\n`
out += `\\newcommand{\\EarlierCommit}{${commit}}\n`
out += `\\newcommand{\\EarlierMustEdges}{${edges}}\n`
out += `\\newcommand{\\EarlierMustClean}{${clean}}\n`
out += `\\newcommand{\\EarlierMustViolations}{${violations}}\n`
out += `\\newcommand{\\EarlierMustFactor}{${(edges / nowEdges).toFixed(0)}}\n`
out += `\\newcommand{\\EarlierGainMust}{${allGained.must}}\n`
out += `\\newcommand{\\EarlierGainFromNode}{${fromNode.must}}\n`
out += `\\newcommand{\\EarlierGainFromAttribution}{${fromAttribution.must}}\n`
out += `\\newcommand{\\EarlierGainFromNodeShare}{${share(fromNode.must, allGained.must)}}\n`

const tex = flag('--tex')
if (tex) { writeFileSync(tex, out); console.error(`wrote ${tex}`) } else { process.stdout.write(out) }
