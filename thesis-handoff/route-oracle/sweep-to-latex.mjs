#!/usr/bin/env node
// The mutation sweep over the demotion rules, as the figures the thesis quotes.
//
// results-must/mutation-sweep.json records, for each rule, the edit that deleted it from a copy
// of the adapter and the suite's result. A rule is covered when the deletion fails a test,
// either at once or after the test added for it. This refuses if any rule is still uncovered.
//
// Usage: node sweep-to-latex.mjs --tex <file>
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const i = process.argv.indexOf('--tex')
const tex = i > -1 ? process.argv[i + 1] : undefined
const r = JSON.parse(readFileSync(path.join(import.meta.dirname, 'results-must', 'mutation-sweep.json'), 'utf8'))
const covered = (m) => !m.survived || /^killed/.test(m.afterAddedTests ?? '')
const open = [...r.mutants.filter((m) => !covered(m)), ...(r.extra ?? []).filter((m) => !/^killed/.test(m.result))]
if (open.length) throw new Error(`rules no test covers: ${open.map((m) => m.id).join(', ')}`)
const lines = ['% Generated by sweep-to-latex.mjs from results-must/mutation-sweep.json. Do not edit by hand.',
  `\\newcommand{\\SweepMutants}{${r.mutants.length}}`,
  `\\newcommand{\\SweepFirstPass}{${r.mutants.filter((m) => !m.survived).length}}`,
  `\\newcommand{\\SweepAdded}{${r.mutants.filter((m) => m.survived).length}}`,
  `\\newcommand{\\SweepExtra}{${(r.extra ?? []).length}}`,
  `\\newcommand{\\SweepCommit}{${r.commit}}`]
if (tex) writeFileSync(tex, lines.join('\n') + '\n')
console.log(lines.slice(1).join(' '))
