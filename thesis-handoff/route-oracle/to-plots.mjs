#!/usr/bin/env node
// Emits the pgfplots figures of Chapter 5 from the harness result files, so the plots
// carry the same numbers as the tables. Never edit the output by hand.
//
// usage: node to-plots.mjs <results-before.json> <results-after.json> <rq4-*.json ...> > generated-plots.tex
//        node to-plots.mjs --rq4-only <rq4-*.json ...> > generated-plots-rq4.tex
//
// The mutation figure is the only plot here whose inputs are still re-measurable: the before
// and after result files the other three are drawn from were produced by a harness version no
// longer on disk, so regenerating the whole file would replace three correct plots with
// era-bound ones. --rq4-only emits the mutation plot alone, under its own macro name, so it
// can be kept current without touching them.

import fs from 'node:fs'
import path from 'node:path'
import { ledger, pct1 } from './report-counts.mjs'

// One line naming the run a generated table came from, so two tables made from different
// runs cannot be read as one measurement.
function provLine(p, note) {
  const e = (p && p.extractor) || {}
  const sha = e.sha ? e.sha.slice(0, 8) : 'unrecorded'
  return '% Extractor ' + sha + (e.source ? ' (' + e.source + ')' : '') +
    ', harness ' + ((p && p.harnessVersion) || 'unrecorded') +
    ((p && p.label) ? ', label ' + p.label : '') + (note ? ', ' + note : '') + '.'
}

const argv = process.argv.slice(2)
const RQ4_ONLY = argv[0] === '--rq4-only'
const [beforeF, afterF, ...corpusArgs] = RQ4_ONLY ? [null, null] : argv
const rq4F = RQ4_ONLY ? argv.slice(1) : corpusArgs
const B = beforeF ? JSON.parse(fs.readFileSync(beforeF, 'utf8')).results : []
const A = afterF ? JSON.parse(fs.readFileSync(afterF, 'utf8')).results : []
const RQ4 = rq4F.map((f) => ({ slug: path.basename(f).replace(/^rq4-/, '').replace(/-attributed\.json$/, ''), ...JSON.parse(fs.readFileSync(f, 'utf8')) }))
const NAME = { realworld: 'realworld', alfresco: 'alfresco', ghostfolio: 'ghostfolio', k8sdash: 'k8s dashboard', bitwarden: 'bitwarden', mifos: 'mifos' }
const sym = B.map((r) => NAME[r.slug]).join(',')
const f1 = (x) => (Math.round(x * 10) / 10).toFixed(1)

let out = '% Generated by to-plots.mjs from the harness result files. Do not edit by hand.\n'
out += RQ4_ONLY
  ? `% Mutation harness ${RQ4[0]?.harnessVersion}, seed ${RQ4[0]?.seed}, quota ${RQ4[0]?.quota} per operator, the attributed run.\n\n`
  : provLine(JSON.parse(fs.readFileSync(afterF, 'utf8')).provenance, 'the attributed run') + '\n\n'
const head = out

// ------------------------------------------------------------ node coverage
out += '\\newcommand{\\PlotCoverage}{%\n\\begin{tikzpicture}\n\\begin{axis}[xbar, width=0.82\\textwidth, height=5.2cm,\n'
out += `  symbolic y coords={${[...B].reverse().map((r) => NAME[r.slug]).join(',')}}, ytick=data, y dir=normal,\n`
out += '  xmin=0, xmax=105, xlabel={declared screens with a node (\\%)}, bar width=7pt,\n'
out += '  nodes near coords={\\pgfmathprintnumber[fixed,precision=1]{\\pgfplotspointmeta}\\%}, nodes near coords style={font=\\scriptsize},\n'
out += '  every axis plot/.append style={fill=accentlight, draw=accent}, axis lines*=left, enlarge y limits=0.12,\n'
out += '  tick label style={font=\\small}, label style={font=\\small}]\n'
out += `\\addplot[fill=accentlight, draw=accent] coordinates {${B.map((r) => `(${f1((r.testC?.coverage ?? 0) * 100)},${NAME[r.slug]})`).join(' ')}};\n`
out += '\\end{axis}\n\\end{tikzpicture}}\n\n'

// ------------------------------------------------------------ loss breakdown, 100% stacked
// Every outcome the classifier can assign, once: the plot is 100 % stacked over all of an
// application's constructs, so a series missing here is a part of the bar that is not drawn.
// The last two series are the table's accounted-for and outside-the-denominator blocks.
const GROUPS = [
  ['Converted', ['CONVERTED_MUST', 'CONVERTED_MAY'], 'fill=good!55, draw=good'],
  ['Attribution', ['ATTRIBUTION_SHARED', 'ATTRIBUTION_SERVICE'], 'fill=accent!70, draw=accent'],
  ['Node defects', ['LAZY_BOUNDARY', 'CONSTANT_PATH', 'COMPONENT_UNLINKED', 'NODE_MISS'], 'fill=warm!70, draw=warm'],
  ['Other losses', ['CONSTANT_TARGET', 'OTHER'], 'fill=muted!50, draw=muted'],
  ['Dynamic or unplaced', ['ACCOUNTED_DYNAMIC', 'ACCOUNTED_UNPLACED'], 'fill=accentlight, draw=accent'],
  ['Excluded', ['QUERY_ONLY', 'EXCLUDED_NO_COMMANDS', 'EXCLUDED_NAMED_OUTLET'], 'fill=mutedlight, draw=muted'],
]
// Refused unless the series account for every construct of every application. A key the
// classifier renamed, as NAMED_OUTLET was, would otherwise drop out of the bar without a sound.
const DRAWN = GROUPS.flatMap(([, keys]) => keys)
for (const r of B) {
  const l = ledger(r)
  const undrawn = Object.keys(l.tally).filter((k) => l.tally[k] && !DRAWN.includes(k))
  if (undrawn.length) throw new Error(`${r.slug}: the loss ledger holds ${undrawn.join(', ')}, which no series of the loss plot covers`)
  const drawn = DRAWN.reduce((a, k) => a + (l.tally[k] ?? 0), 0)
  if (drawn !== l.constructs) throw new Error(`${r.slug}: the loss plot draws ${drawn} constructs and the ledger holds ${l.constructs}`)
}
out += '\\newcommand{\\PlotLoss}{%\n\\begin{tikzpicture}\n\\begin{axis}[xbar stacked, width=0.82\\textwidth, height=6cm,\n'
out += `  symbolic y coords={${[...B].reverse().map((r) => NAME[r.slug]).join(',')}}, ytick=data,\n`
out += '  xmin=0, xmax=100, xlabel={share of navigation constructs (\\%)}, bar width=9pt,\n'
out += '  legend style={at={(0.5,1.03)}, anchor=south, legend columns=3, font=\\scriptsize, draw=none},\n'
out += '  axis lines*=left, enlarge y limits=0.12, tick label style={font=\\small}, label style={font=\\small}]\n'
for (const [label, keys, style] of GROUPS) {
  const pts = B.map((r) => {
    const n = keys.reduce((s, k) => s + (ledger(r).tally[k] || 0), 0)
    return `(${pct1(n, ledger(r).constructs)},${NAME[r.slug]})`
  })
  out += `\\addplot[${style}] coordinates {${pts.join(' ')}};\n\\addlegendentry{${label}}\n`
}
out += '\\end{axis}\n\\end{tikzpicture}}\n\n'

// ------------------------------------------------------------ before / after conversion
out += '\\newcommand{\\PlotBeforeAfter}{%\n\\begin{tikzpicture}\n\\begin{axis}[ybar, width=0.92\\textwidth, height=5.6cm,\n'
out += `  symbolic x coords={${sym}}, xtick=data, x tick label style={font=\\small, rotate=20, anchor=north east},\n`
out += '  ymin=0, ymax=45, ylabel={conversion (\\%)}, bar width=9pt, enlarge x limits=0.1,\n'
out += '  nodes near coords={\\pgfmathprintnumber[fixed,precision=1]{\\pgfplotspointmeta}}, nodes near coords style={font=\\tiny},\n'
out += '  legend style={at={(0.5,1.03)}, anchor=south, legend columns=2, font=\\scriptsize, draw=none}, axis lines*=left, label style={font=\\small}]\n'
out += `\\addplot[fill=mutedlight, draw=muted] coordinates {${B.map((r) => `(${NAME[r.slug]},${pct1(ledger(r).tally.CONVERTED_MUST || 0, ledger(r).constructs)})`).join(' ')}};\n\\addlegendentry{baseline}\n`
out += `\\addplot[fill=accent!70, draw=accent] coordinates {${A.map((r) => `(${NAME[r.slug]},${pct1(ledger(r).tally.CONVERTED_MUST || 0, ledger(r).constructs)})`).join(' ')}};\n\\addlegendentry{with attribution}\n`
out += '\\end{axis}\n\\end{tikzpicture}}\n\n'

// The corpus plots above are drawn from result files an earlier harness produced; in
// --rq4-only mode they are discarded and only the mutation plot is emitted.
if (RQ4_ONLY) out = head

// ------------------------------------------------------------ mutation by operator
const OPS = [['RENAME_PATH', 'rename path'], ['DELETE_ROUTERLINK', 'delete link'], ['CHANGE_NAV_TARGET', 'retarget navigate'], ['REMOVE_GUARD', 'remove guard']]
const sum = (op, k) => RQ4.reduce((s, r) => s + (r.perOperator?.[op]?.[k] || 0), 0)
out += `\\newcommand{\\${RQ4_ONLY ? 'PlotMutationRQ' : 'PlotMutation'}}{%\n\\begin{tikzpicture}\n\\begin{axis}[xbar stacked, width=0.78\\textwidth, height=4.8cm,\n`
out += `  symbolic y coords={${[...OPS].reverse().map((o) => o[1]).join(',')}}, ytick=data,\n`
out += '  xmin=0, xlabel={scored mutants, all three applications}, bar width=9pt,\n'
out += '  legend style={at={(0.5,1.03)}, anchor=south, legend columns=3, font=\\scriptsize, draw=none},\n'
out += '  axis lines*=left, enlarge y limits=0.15, tick label style={font=\\small}, label style={font=\\small}]\n'
out += `\\addplot[fill=good!55, draw=good] coordinates {${OPS.map(([k, l]) => `(${sum(k, 'detected')},${l})`).join(' ')}};\n\\addlegendentry{detected}\n`
out += `\\addplot[fill=warm!70, draw=warm] coordinates {${OPS.map(([k, l]) => `(${sum(k, 'missed')},${l})`).join(' ')}};\n\\addlegendentry{missed}\n`
out += `\\addplot[fill=muted!50, draw=muted] coordinates {${OPS.map(([k, l]) => `(${sum(k, 'wrong')},${l})`).join(' ')}};\n\\addlegendentry{wrong change}\n`
out += '\\end{axis}\n\\end{tikzpicture}}\n'

process.stdout.write(out)
