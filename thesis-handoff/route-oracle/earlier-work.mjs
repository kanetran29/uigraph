#!/usr/bin/env node
/**
 * Applies the input restrictions Oshima and Kishi state for their extraction (no `children` attribute and no route
 * parameters in the routing declarations) to the route tables the independent route parser reads, and writes how many
 * corpus applications those restrictions admit. A route with `children` or `loadChildren` is a nested route tree
 * (the parser's PREFIX kind); a path segment starting with ':' is a route parameter. Either one excludes the application.
 *
 * Usage: node earlier-work.mjs --dir <dir holding <slug>.fin.C.json> --apps realworld,alfresco,... --tex <out.tex>
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** Reads `--name value` pairs from the command line. */
function args(argv) {
  const out = {}
  for (let i = 2; i < argv.length; i += 2) out[argv[i].replace(/^--/, '')] = argv[i + 1]
  return out
}

const a = args(process.argv)
const apps = a.apps.split(',')
const per = apps.map((slug) => {
  const routes = JSON.parse(readFileSync(join(a.dir, `${slug}.fin.C.json`), 'utf8')).routes
  const params = routes.filter((r) => (r.path ?? '').split('/').some((s) => s.startsWith(':'))).length
  const nested = routes.filter((r) => r.kind === 'PREFIX').length
  return { slug, routes: routes.length, params, nested }
})
for (const p of per) console.log(`${p.slug}: ${p.routes} routes, ${p.params} with a parameter, ${p.nested} with children or loadChildren`)
const tag = { realworld: 'Realworld', alfresco: 'Alfresco', ghostfolio: 'Ghostfolio', k8sdash: 'Kdash', bitwarden: 'Bitwarden', mifos: 'Mifos' }
let tex = '% Generated by earlier-work.mjs from the independent route parser\'s output. Do not edit by hand.\n'
for (const [k, v] of [
  ['EarlierWorkApps', per.length],
  ['EarlierWorkParamApps', per.filter((p) => p.params > 0).length],
  ['EarlierWorkNestedApps', per.filter((p) => p.nested > 0).length],
  ['EarlierWorkAdmittedApps', per.filter((p) => p.params === 0 && p.nested === 0).length],
]) tex += `\\newcommand{\\${k}}{${v}}\n`
for (const p of per) {
  const t = tag[p.slug] ?? p.slug.replace(/[^A-Za-z]/g, '')
  tex += `\\newcommand{\\EarlierWorkParams${t}}{${p.params}}\n\\newcommand{\\EarlierWorkNested${t}}{${p.nested}}\n`
}
writeFileSync(a.tex, tex)
