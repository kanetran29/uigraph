#!/usr/bin/env node
// Generate the LaTeX result tables of the thesis from results.json, so that no number in
// the results chapter is typed by hand.
//
// Usage: node to-latex.mjs results/results.json > generated-tables.tex
// The output defines one macro per table: \TabConversion, \TabCoverage, \TabLoss.

import fs from 'node:fs'
import path from 'node:path'
import { conversion, inScope } from './report-counts.mjs'

const file = process.argv[2]
const data = JSON.parse(fs.readFileSync(file, 'utf8'))
const R = data.results
const rawDir = path.join(path.dirname(file), 'raw')
const NAME = { realworld: 'realworld', alfresco: 'alfresco', ghostfolio: 'ghostfolio', k8sdash: 'k8s dashboard', bitwarden: 'bitwarden', mifos: 'mifos' }
const short = { realworld: 'rw', alfresco: 'alf', ghostfolio: 'gf', k8sdash: 'k8s', bitwarden: 'bw', mifos: 'mif' }
// The thesis quotes the All row as the corpus total, so a results.json that is not exactly the applications NAME and
// short label is refused before anything is read: one missing makes the row a subset total, and one they do not label
// prints `undefined` for its rows and changes the total. NAME is kept here rather than read from corpus.json, which holds
// no display names or short labels, so reading the slug list from it would leave these two tables to be kept in step by
// hand all the same.
const absent = Object.keys(NAME).filter((s) => !R.some((r) => r.slug === s))
const unlabelled = R.filter((r) => !NAME[r.slug] || !short[r.slug]).map((r) => r.slug)
const problems = []
if (absent.length) problems.push(`holds ${R.length - unlabelled.length} of ${Object.keys(NAME).length} applications, missing ${absent.join(', ')}: the All row would total a subset`)
if (unlabelled.length) problems.push(`holds ${unlabelled.join(', ')}, which NAME and short do not label: its rows would print undefined and the All row would total a different set`)
if (problems.length) throw new Error(`${file} ${problems.join('; and ')}`)
const pct = (v) => (v === null || v === undefined ? '--' : `${(v * 100).toFixed(1)}\\%`)
/** The conversion cell of the table, from the ledger's counts and not from results.json's `conversion`, which is rounded to four places already. */
const convCell = (r) => (conversion(r) === null ? '--' : `${conversion(r).toFixed(1)}\\%`)
const prov = data.provenance
let out = `% Generated by to-latex.mjs from ${path.basename(file)}. Do not edit by hand.\n`
// The header carries what makes a figure unpublishable, not just where it came from: a +dirty or local-checkout
// extractor, and a failed enforcement check. Each is printed only when results.json has it, so a file written
// before run-all.mjs recorded it keeps its old header byte for byte.
const sha = prov.extractor.sha.replace(/^([0-9a-f]{8})[0-9a-f]*/, '$1')
out += `% Extractor ${sha}${prov.extractor.source ? ` (${prov.extractor.source})` : ''}, harness ${prov.harnessVersion}${prov.label ? `, label ${prov.label}` : ''}, run ${prov.startedAt.slice(0, 10)}.\n`
if (prov.enforcementFailures?.length) out += `% ENFORCEMENT FAILED -- do not publish. ${prov.enforcementFailures.map((f) => `${f.slug}/${f.script} (${f.status})`).join(', ')}.\n`
out += `\n`

// ---------------------------------------------------------------- conversion
out += `\\newcommand{\\TabConversion}{%\n\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n`
out += `Application & Constructs & In scope & Nodes & Must & May & Must conversion \\\\\n\\midrule\n`
for (const r of R) out += `${NAME[r.slug]} & ${r.totalConstructs} & ${r.loss?.tally ? inScope(r.loss) : '--'} & ${r.graph?.nodes ?? '--'} & ${r.graph?.must ?? '--'} & ${r.graph?.may ?? '--'} & ${convCell(r)} \\\\\n`
out += `\\bottomrule\n\\end{tabular}}\n\n`
// The constructs column again, one macro per application, for the sentences that quote it.
const MACRO = { realworld: 'Realworld', alfresco: 'Alfresco', ghostfolio: 'Ghostfolio', k8sdash: 'Kdash', bitwarden: 'Bitwarden', mifos: 'Mifos' }
for (const r of R) if (MACRO[r.slug]) out += `\\newcommand{\\Constructs${MACRO[r.slug]}}{${r.totalConstructs}}\n`
out += `\n`

// ---------------------------------------------------------------- node coverage
// The differential test disagrees in both directions. Reporting only the matched column
// would give recall and hide precision, so the nodes the parser holds no declared screen
// for are reported beside it.
out += `\\newcommand{\\TabCoverage}{%\n\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n`
// headers kept short: the caption carries the full meaning of each column
out += `Application & Declared & Nodes & Matched & Coverage & Unmatched & Blind spots \\\\\n\\midrule\n`
let gN = 0, gX = 0
for (const r of R) {
  const C = JSON.parse(fs.readFileSync(path.join(rawDir, `${r.slug}.C.json`), 'utf8'))
  const c = requireComparison(r.slug, C)
  const extra = c.extraNodes?.length ?? 0
  gN += c.graphNodes ?? 0; gX += extra
  out += `${NAME[r.slug]} & ${c.declaredScreens ?? '--'} & ${c.graphNodes ?? '--'} & ${c.matched ?? '--'} & ${pct(c.coverage)} & ${extra} & ${C.blindSpots?.length ?? 0} \\\\\n`
}
out += `\\midrule\nAll & & ${gN} & & & ${gX} & \\\\\n`
out += `\\bottomrule\n\\end{tabular}}\n\n`

/** A raw route file with no comparison block zeroed a column and quietly reduced the
 *  corpus node total, so it is refused: a missing measurement is not a measurement of zero. */
function requireComparison(slug, C) {
  if (!C || !C.comparison) throw new Error(`${slug}: its raw route file holds no comparison block, so its nodes would be dropped from the total and its unmatched count printed as 0`)
  return C.comparison
}

// ---------------------------------------------------------------- loss breakdown
const ROWS = [
  ['CONVERTED_MUST', 'Converted, must'],
  ['CONVERTED_MAY', 'Converted, may'],
  null,
  ['ATTRIBUTION_SHARED', 'Attribution, shared component'],
  ['ATTRIBUTION_SERVICE', 'Attribution, service'],
  ['LAZY_BOUNDARY', 'Lazy boundary'],
  ['CONSTANT_PATH', 'Constant path'],
  ['COMPONENT_UNLINKED', 'Component unlinked'],
  ['CONSTANT_TARGET', 'Constant target'],
  ['NODE_MISS', 'Node missing, other'],
  ['OTHER', 'Other'],
  null,
  // Accounted for rather than lost: the destination is one only the run time knows, or the
  // destination reads but the screen the site fires from does not.
  ['ACCOUNTED_DYNAMIC', 'Dynamic destination'],
  ['ACCOUNTED_UNPLACED', 'Source the analysis cannot place'],
  null,
  // Outside the denominator. EXCLUDED_NAMED_OUTLET was called NAMED_OUTLET when this table
  // was written and the row kept the old key, so it printed 0 in all six columns for a class
  // with real members -- which is how the table came to be short of its own total.
  ['QUERY_ONLY', 'Query only (not a transition)'],
  ['EXCLUDED_NO_COMMANDS', 'Excluded: names no destination'],
  ['EXCLUDED_NAMED_OUTLET', 'Excluded: navigates a named outlet'],
]
// The table says it assigns every construct to one outcome, so it is refused unless it does.
// A row whose key the classifier has renamed prints zero and the remainder goes unaccounted
// for, which is how 186 constructs went missing from a published table with nothing failing.
const ROW_KEYS = ROWS.filter(Boolean).map(([k]) => k)
for (const r of R) {
  const tally = r.loss?.tally ?? {}
  const unrowed = Object.keys(tally).filter((k) => !ROW_KEYS.includes(k) && tally[k])
  if (unrowed.length) throw new Error(`${r.slug}: the loss ledger holds ${unrowed.join(', ')}, which this table has no row for; every construct must appear in exactly one row`)
  const summed = ROW_KEYS.reduce((a, k) => a + (tally[k] ?? 0), 0)
  if (summed !== (r.loss?.constructs ?? 0)) throw new Error(`${r.slug}: the rows sum to ${summed} and the table prints ${r.loss?.constructs ?? 0} constructs; the difference is unaccounted for`)
}
out += `\\newcommand{\\TabLoss}{%\n\\begin{tabular}{@{}l${'r'.repeat(R.length)}r@{}}\n\\toprule\n`
out += `Outcome & ${R.map((r) => short[r.slug]).join(' & ')} & Total \\\\\n\\midrule\n`
for (const row of ROWS) {
  if (!row) { out += `\\midrule\n`; continue }
  const [k, label] = row
  const vals = R.map((r) => r.loss?.tally?.[k] ?? 0)
  out += `${label} & ${vals.join(' & ')} & ${vals.reduce((a, b) => a + b, 0)} \\\\\n`
}
const tot = R.map((r) => r.loss?.constructs ?? 0)
out += `\\midrule\nAll constructs & ${tot.join(' & ')} & ${tot.reduce((a, b) => a + b, 0)} \\\\\n`
out += `\\bottomrule\n\\end{tabular}}\n`

// The test-source cross-check's own figures, which two chapters quote and neither generated.
{
  const d = R.find((r) => r.slug === 'alfresco')
  const e2e = d?.testD
  if (e2e && typeof e2e.recall === 'number') {
    const n = typeof e2e.urls === 'number' ? e2e.urls : (e2e.rows ?? []).length
    out += `\n% The test-source cross-check on the one application that has a usable suite.\n`
    out += `\\newcommand{\\EtoERecallAlfresco}{${Math.round(e2e.recall * n)} of ${n}}\n`
    out += `\\newcommand{\\EtoERowsAlfresco}{${n}}\n`
    out += `\\newcommand{\\EtoERateAlfresco}{${(e2e.recall * 100).toFixed(1)}\\,\\%}\n`
  }
}

out += `\n% The corpus construct total, which the chapter states in prose.\n`
out += `\\newcommand{\\RoundTwoInScopeAll}{${R.reduce((a, r) => a + (r.totalConstructs || 0), 0)}}\n`

process.stdout.write(out)
