#!/usr/bin/env node
// The static ceiling: every transition the graph still misses, in the applications' own
// end-to-end suites and in the structural references, classed as inside the static boundary
// (fixed by the frontend source, a library under node_modules, or static configuration in the
// repository, so a better reader would recover it) or outside it (a target or route the backend
// supplies, configuration fetched at run time, user input that changes the destination screen).
//
// The classes are the author's reading, recorded per miss in a JSON file with the gap it belongs
// to, an example site and the fix. This script only joins them to the scorers' output: it refuses
// a miss no class names, and a class that names no miss, so the reading cannot go stale unseen.
//
// Usage: node ceiling.mjs --classes <file> [--gt <app>=<score-ground-truth --json output>]...
//          [--e2e <app>=<e2e-nav results dir>]... [--tex <file>]
// The structural references are read at their full level; an end-to-end miss weighs one pair, a
// reference miss the (site, screen) pairs it leaves out.
import { readFileSync, writeFileSync } from 'node:fs'
import { score } from '../e2e-nav/score.mjs'

const argv = process.argv.slice(2)
const flag = (n) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : undefined }
const many = (n) => argv.filter((_, i) => argv[i - 1] === n).map((s) => {
  const i = s.indexOf('=')
  if (i < 0) throw new Error(`${n} wants <app>=<path>, got ${s}`)
  return [s.slice(0, i), s.slice(i + 1)]
})
const classesPath = flag('--classes')
if (!classesPath) {
  console.error('usage: node ceiling.mjs --classes <file> [--gt <app>=<json>]... [--e2e <app>=<dir>]... [--tex <file>]')
  process.exit(2)
}

/** Each scored source: its name, the pairs it scores, those the graph holds, and its misses with their weights. */
const sources = []
for (const [app, file] of many('--gt')) {
  const full = JSON.parse(readFileSync(file, 'utf8')).levels.find((l) => l.level === 'full')
  if (!full) throw new Error(`${file} has no full level`)
  sources.push({ key: `gt:${app}`, macro: `Gt${cap(app)}`, total: full.correct + full.missing, held: full.correct,
    misses: full.missedSites.map((m) => ({ id: m.site, weight: m.missing })) })
}
for (const [app, dir] of many('--e2e')) {
  const r = score(dir)
  sources.push({ key: `e2e:${app}`, macro: `EtoE${cap(app)}`, total: r.pairs, held: r.hit,
    misses: r.missed.map((m) => ({ id: `${m.from} -> ${m.to}`, weight: 1 })) })
}

const classes = JSON.parse(readFileSync(classesPath, 'utf8')).misses
const problems = []
const classOf = new Map()
for (const c of classes) {
  if (c.boundary !== 'inside' && c.boundary !== 'outside') problems.push(`${c.source} ${c.id}: boundary must be inside or outside`)
  classOf.set(`${c.source}\u0000${c.id}`, c)
}
const seen = new Set()
for (const s of sources) {
  for (const m of s.misses) {
    const k = `${s.key}\u0000${m.id}`
    seen.add(k)
    if (!classOf.has(k)) problems.push(`unclassified: ${s.key} ${m.id}`)
  }
}
for (const c of classes) if (!seen.has(`${c.source}\u0000${c.id}`)) problems.push(`${c.source} ${c.id}: the class names no miss`)
if (problems.length) {
  console.error(problems.join('\n'))
  process.exit(1)
}

/** An application name as it may stand in a macro name: letters only, first one upper case. */
function cap(name) {
  const letters = name.replace(/[^A-Za-z]/g, '')
  return letters.charAt(0).toUpperCase() + letters.slice(1)
}
const pc = (n, d) => `${(d ? (100 * n) / d : 0).toFixed(1)}\\,\\%`
/** Text set verbatim in LaTeX: its special characters escaped. */
const esc = (t) => String(t).replace(/[\\&%$#_{}~^]/g, (ch) => (ch === '\\' ? '\\textbackslash{}' : ch === '~' ? '\\textasciitilde{}' : ch === '^' ? '\\textasciicircum{}' : `\\${ch}`))

let out = '% generated by ceiling.mjs; do not edit\n'
let all = 0, allInside = 0
/** Pairs per gap, in the order the class file first names each gap. */
const gaps = new Map()
for (const s of sources) {
  let inside = 0, missing = 0
  for (const m of s.misses) {
    const c = classOf.get(`${s.key}\u0000${m.id}`)
    missing += m.weight
    if (c.boundary === 'inside') inside += m.weight
    const g = gaps.get(c.gap) ?? { gap: c.gap, example: c.example, boundary: c.boundary, fix: c.fix, pairs: 0 }
    if (g.boundary !== c.boundary) throw new Error(`gap "${c.gap}" is classed both inside and outside`)
    g.pairs += m.weight
    gaps.set(c.gap, g)
  }
  all += missing
  allInside += inside
  out += `\\newcommand{\\Ceil${s.macro}Missing}{${missing}}\n`
  out += `\\newcommand{\\Ceil${s.macro}Inside}{${inside}}\n`
  out += `\\newcommand{\\Ceil${s.macro}Outside}{${missing - inside}}\n`
  out += `\\newcommand{\\Ceil${s.macro}Now}{${pc(s.held, s.total)}}\n`
  out += `\\newcommand{\\Ceil${s.macro}Ceiling}{${pc(s.held + inside, s.total)}}\n`
}
out += `\\newcommand{\\CeilMissing}{${all}}\n`
out += `\\newcommand{\\CeilInside}{${allInside}}\n`
out += `\\newcommand{\\CeilOutside}{${all - allInside}}\n`
out += `\\newcommand{\\CeilInsideShare}{${pc(allInside, all)}}\n`
/** An example site set with \\path, which breaks it at slashes; the characters \\path cannot carry in a macro argument are refused. */
const site = (t) => {
  if (/[{}%#\\]/.test(t)) throw new Error(`example "${t}" holds a character \\path cannot carry`)
  return `\\path{${t}}`
}
const rows = [...gaps.values()].map((g) => `${esc(g.gap)} & ${site(g.example)} & ${g.boundary} & ${esc(g.fix)} & ${g.pairs} \\\\`)
out += `\\newcommand{\\TabCeilGaps}{${rows.join('\n')}}\n`

const tex = flag('--tex')
if (tex) writeFileSync(tex, out)
else process.stdout.write(out)
