#!/usr/bin/env node
// The witness check's verdict on the current must tier, summed over the corpus.
//
// witness-check.mjs judges one application and writes its findings with --json. This reads
// those files for all six applications and writes the two figures the chapter quotes, refusing
// when an application is missing, so a tier judged on part of the corpus is never reported as
// the corpus's.
//
// Usage: node must-witness.mjs --dir <dir with <app>.json> --tex <file>
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const argv = process.argv.slice(2)
const flag = (n) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : undefined }
const dir = flag('--dir'), tex = flag('--tex')
if (!dir || !tex) { console.error('usage: node must-witness.mjs --dir <dir> --tex <file>'); process.exit(2) }

const APPS = ['realworld', 'alfresco', 'ghostfolio', 'k8sdash', 'bitwarden', 'mifos']
let edges = 0, violations = 0
for (const app of APPS) {
  const f = path.join(dir, `${app}.json`)
  if (!existsSync(f)) throw new Error(`no witness check for ${app} at ${f}`)
  const r = JSON.parse(readFileSync(f, 'utf8'))
  edges += r.mustEdges
  violations += r.mustBad.length
}
writeFileSync(tex, ['% Generated by must-witness.mjs from the witness-check results. Do not edit by hand.',
  `\\newcommand{\\MustWitnessEdges}{${edges}}`,
  `\\newcommand{\\MustWitnessViolations}{${violations}}`].join('\n') + '\n')
console.log(`must tier: ${edges} edges, ${violations} violations`)
