#!/usr/bin/env node
// The witness check's verdict on the current must tier, summed over the corpus.
//
// witness-check.mjs judges one application and writes its findings with --json. This reads
// those files for all six applications and writes the two figures the chapter quotes, refusing
// when an application is missing, so a tier judged on part of the corpus is never reported as
// the corpus's, or when a run did not test destinations against the independent route set. A
// failure is counted per edge.
//
// Usage: node must-witness.mjs --dir <dir with <app>.json> --tex <file>
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { extractorStamp } from './provenance.mjs'

const argv = process.argv.slice(2)
const flag = (n) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : undefined }
const dir = flag('--dir'), tex = flag('--tex')
if (!dir || !tex) { console.error('usage: node must-witness.mjs --dir <dir> --tex <file>'); process.exit(2) }

const APPS = ['realworld', 'alfresco', 'ghostfolio', 'k8sdash', 'bitwarden', 'mifos']
let edges = 0, violations = 0, cited = 0, merged = 0
const shares = {}
for (const app of APPS) {
  const f = path.join(dir, `${app}.json`)
  if (!existsSync(f)) throw new Error(`no witness check for ${app} at ${f}`)
  const r = JSON.parse(readFileSync(f, 'utf8'))
  // The check the thesis defines also tests each destination against the independent route set.
  if (r.destinationsChecked !== true) throw new Error(`${app}: the witness check ran without --routes, so destinations were not tested`)
  edges += r.mustEdges
  violations += r.mustEdges - r.mustClean
  // How much of the evidence for the whole graph sits in merged citations, the part the check
  // once left unread.
  cited += r.sitesCited
  merged += r.mergedSites
  shares[app] = r.mergedSites / r.sitesCited
}
writeFileSync(tex, ['% Generated by must-witness.mjs from the witness-check results. Do not edit by hand.', extractorStamp(),
  `\\newcommand{\\MustWitnessEdges}{${edges}}`,
  `\\newcommand{\\MustWitnessViolations}{${violations}}`,
  `\\newcommand{\\WitnessMergedShareRealworld}{${(shares.realworld * 100).toFixed(1)}\\,\\%}`,
  `\\newcommand{\\WitnessMergedShareAll}{${((merged / cited) * 100).toFixed(1)}\\,\\%}`,
  `\\newcommand{\\WitnessMergedShareMax}{${(Math.max(...Object.values(shares)) * 100).toFixed(1)}\\,\\%}`].join('\n') + '\n')
console.log(`must tier: ${edges} edges, ${violations} violations`)
