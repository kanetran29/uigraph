#!/usr/bin/env node
// The witness check's verdict on the current must tier, summed over the corpus.
//
// witness-check.mjs judges one application and writes its findings with --json. This reads
// those files for all six applications and writes the figures the chapter quotes, refusing
// when an application is missing, so a tier judged on part of the corpus is never reported as
// the corpus's, or when a run did not test destinations against the independent route set. A
// failure is counted per edge, and so is an unread edge: a must edge that cites a construct whose
// destination the check could not read, which passes nothing and fails nothing. The merged share
// counts citations (one per edge and cited construct, so a construct that sixty edges cite is
// counted sixty times), not distinct constructs.
//
// Usage: node must-witness.mjs --dir <dir with <app>.json> --tex <file>
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { extractorStamp } from './provenance.mjs'

const argv = process.argv.slice(2)
const flag = (n) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : undefined }
const dir = flag('--dir'), tex = flag('--tex')
if (!dir || !tex) { console.error('usage: node must-witness.mjs --dir <dir> --tex <file>'); process.exit(2) }

const APPS = ['realworld', 'alfresco', 'ghostfolio', 'k8sdash', 'bitwarden', 'mifos']
let edges = 0, violations = 0, unread = 0, cited = 0, merged = 0
const shares = {}
for (const app of APPS) {
  const f = path.join(dir, `${app}.json`)
  if (!existsSync(f)) throw new Error(`no witness check for ${app} at ${f}`)
  const r = JSON.parse(readFileSync(f, 'utf8'))
  // The check the thesis defines also tests each destination against the independent route set.
  if (r.destinationsChecked !== true) throw new Error(`${app}: the witness check ran without --routes, so destinations were not tested`)
  edges += r.mustEdges
  violations += r.mustEdges - r.mustClean
  // A result file from before the check counted these cannot say how many edges it left unread.
  if (!Number.isInteger(r.mustUnread)) throw new Error(`${app}: the witness check recorded no count of must edges whose destination it could not read; run it again with this version of witness-check.mjs`)
  unread += r.mustUnread
  // How many of the citations in the whole graph are merged ones, the part the check once left
  // unread. A citation is one edge-and-construct pair.
  cited += r.sitesCited
  merged += r.mergedSites
  shares[app] = r.mergedSites / r.sitesCited
}
writeFileSync(tex, ['% Generated by must-witness.mjs from the witness-check results. Do not edit by hand.', extractorStamp(),
  `\\newcommand{\\MustWitnessEdges}{${edges}}`,
  `\\newcommand{\\MustWitnessViolations}{${violations}}`,
  `\\newcommand{\\MustWitnessUnread}{${unread}}`,
  `\\newcommand{\\WitnessMergedCitationShareRealworld}{${(shares.realworld * 100).toFixed(1)}\\,\\%}`,
  `\\newcommand{\\WitnessMergedCitationShareAll}{${((merged / cited) * 100).toFixed(1)}\\,\\%}`,
  `\\newcommand{\\WitnessMergedCitationShareMax}{${(Math.max(...Object.values(shares)) * 100).toFixed(1)}\\,\\%}`].join('\n') + '\n')
console.log(`must tier: ${edges} edges, ${violations} violations, ${unread} edges whose destination was not read`)
