#!/usr/bin/env node
// How much of the must tier rests on the route-order assumption.
//
// The router joins route tables registered apart in the order their providers are registered,
// which the extractor does not read; it assumes a catch-all in one such table is matched after
// every route of the others, and names each catch-all it dismissed in a `route-order` note. This
// extracts each application with the assumption and again without it (UIGRAPH_ROUTE_ORDER=unread,
// under which such a catch-all is a rival like any other), and counts the must edges and the
// constructs behind them that only the assumption keeps on the tier.
//
// Usage: pnpm exec tsx route-order.mjs --corpus <dir> --out <dir> [--tex <file>]
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { buildProject, extractGraph } from '../../packages/adapter-angular/src/extract.ts'
import { extractorStamp } from './provenance.mjs'

const argv = process.argv.slice(2)
const flag = (n) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : undefined }
const corpus = flag('--corpus'), outDir = flag('--out'), tex = flag('--tex')
if (!corpus || !outDir) { console.error('usage: pnpm exec tsx route-order.mjs --corpus <dir> --out <dir> [--tex <file>]'); process.exit(2) }
const APPS = { realworld: '.', alfresco: 'projects/aca-content', ghostfolio: 'apps/client', k8sdash: 'modules/web', bitwarden: 'apps/web', mifos: '.' }

/** The must edges of an extraction, and the constructs that earn must behind them, as the census counts them. */
function mustOf(dir) {
  const { graph, soundiness } = extractGraph(buildProject(dir), dir, { attribution: true })
  const must = graph.edges.filter((e) => e.modality === 'must')
  const sites = new Set(must.flatMap((e) => [e.witness, ...(e.mergedWitnesses ?? [])]).filter((w) => w && (w.modality ?? 'must') === 'must').map((w) => `${w.file}:${w.loc?.line}`))
  return { edges: must.length, sites: sites.size, noted: soundiness.some((n) => n.kind === 'route-order') }
}

mkdirSync(outDir, { recursive: true })
const rows = []
for (const [slug, sub] of Object.entries(APPS)) {
  const dir = path.resolve(corpus, slug, sub)
  const withIt = mustOf(dir)
  process.env.UIGRAPH_ROUTE_ORDER = 'unread'
  const without = mustOf(dir)
  delete process.env.UIGRAPH_ROUTE_ORDER
  // Dropping an assumption can only add rivals, so it can only take edges off the tier.
  if (without.edges > withIt.edges || without.sites > withIt.sites) throw new Error(`${slug}: the tier grew without the assumption (${withIt.edges} -> ${without.edges} edges), which an added rival cannot do`)
  rows.push({ slug, edges: withIt.edges, edgesWithout: without.edges, sites: withIt.sites, sitesWithout: without.sites, noted: withIt.noted })
}
const sum = (k) => rows.reduce((a, r) => a + r[k], 0)
const resting = rows.filter((r) => r.edges > r.edgesWithout)
writeFileSync(path.join(outDir, 'route-order.json'), JSON.stringify({ rows }, null, 2) + '\n')
if (tex) {
  writeFileSync(tex, ['% Generated by route-order.mjs. Do not edit by hand.', extractorStamp(),
    `\\newcommand{\\RouteOrderMust}{${sum('edges')}}`,
    `\\newcommand{\\RouteOrderMustWithout}{${sum('edgesWithout')}}`,
    `\\newcommand{\\RouteOrderResting}{${sum('edges') - sum('edgesWithout')}}`,
    `\\newcommand{\\RouteOrderSites}{${sum('sites')}}`,
    `\\newcommand{\\RouteOrderSitesWithout}{${sum('sitesWithout')}}`,
    `\\newcommand{\\RouteOrderRestingSites}{${sum('sites') - sum('sitesWithout')}}`,
    `\\newcommand{\\RouteOrderRestingApps}{${resting.length}}`,
    `\\newcommand{\\RouteOrderRestingWhere}{${resting.map((r) => r.slug).join(', ') || 'none'}}`,
    `\\newcommand{\\RouteOrderNotedApps}{${rows.filter((r) => r.noted).length}}`].join('\n') + '\n')
}
console.log(JSON.stringify(rows))
