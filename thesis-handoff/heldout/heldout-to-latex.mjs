#!/usr/bin/env node
/**
 * Writes the held-out figures (heldout/PREREGISTRATION.txt, measures H1-H6) as LaTeX macros, from the result files
 * heldout.sh leaves in one directory per run: provenance.txt and, per application, <slug>.C.json (independent route
 * parser), <slug>.B.json (witness check), <slug>.L.json and <slug>.L0.json (loss breakdown with and without
 * attribution). The ratios use the corpus definitions of route-oracle/report-counts.mjs.
 *
 * Usage: node heldout-to-latex.mjs --dir results --apps peertube=Peertube,spotify=Spotify --tex out.tex
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, basename } from 'node:path'
import { conversion, share } from '../route-oracle/report-counts.mjs'

/** Reads `--name value` pairs from the command line. */
function args(argv) {
  const out = {}
  for (let i = 2; i < argv.length; i += 2) out[argv[i].replace(/^--/, '')] = argv[i + 1]
  return out
}

/** A share of `n` in `d` as the thesis prints it, or a dash when `d` is zero. */
const pc = (n, d) => (d > 0 ? `${share(n, d).toFixed(1)}\\,\\%` : '--')

const ATTR = ['ATTRIBUTION_SHARED', 'ATTRIBUTION_SERVICE']
const a = args(process.argv)
const prov = readFileSync(join(a.dir, 'provenance.txt'), 'utf8')
const rd = (f) => JSON.parse(readFileSync(join(a.dir, f), 'utf8'))
let tex = `% Generated by heldout/heldout-to-latex.mjs from heldout/${basename(a.dir)}. Do not edit by hand.\n% ${prov.split('\n')[0]}\n`
for (const spec of a.apps.split(',')) {
  const [slug, tag] = spec.split('=')
  const completed = new RegExp(`^${slug} map-attr exit=0`, 'm').test(prov)
  const C = rd(`${slug}.C.json`), B = rd(`${slug}.B.json`), L = rd(`${slug}.L.json`), L0 = rd(`${slug}.L0.json`)
  const after = new Map(L.rows.map((r) => [r.at, r.cls]))
  const lost0 = L0.rows.filter((r) => ATTR.includes(r.cls))
  const recovered = lost0.filter((r) => /^CONVERTED_/.test(after.get(r.at) ?? '')).length
  const params = C.routes.some((r) => (r.path ?? '').split('/').some((s) => s.startsWith(':')))
  const nested = C.routes.some((r) => r.kind === 'PREFIX')
  const conv = conversion({ loss: L })
  const m = {
    Completed: completed ? 'yes' : 'no',
    Nodes: `${C.comparison.matched} of ${C.comparison.declaredScreens}`,
    NodeCoverage: pc(C.comparison.matched, C.comparison.declaredScreens),
    BlindSpots: (C.blindSpots ?? []).length,
    Constructs: L.inScope,
    MustConversion: conv === null ? '--' : `${conv.toFixed(1)}\\,\\%`,
    RecoveredShare: pc(L.recovered, L.inScope),
    AccountedShare: pc(L.recovered + L.accounted, L.inScope),
    MustConverted: L.tally.CONVERTED_MUST ?? 0,
    MustEdges: B.mustEdges,
    WitnessFailures: B.mustEdges - B.mustClean - B.mustUnread,
    WitnessUnread: B.mustUnread,
    AttrLost: lost0.length,
    AttrRecovered: recovered,
    AttrRecoveredShare: pc(recovered, lost0.length),
    // With no route read, the restrictions cannot be applied, so the answer is unknown, not 'admitted'.
    EarlierAdmitted: C.routes.length === 0 ? '--' : params || nested ? 'no' : 'yes',
  }
  for (const [k, v] of Object.entries(m)) tex += `\\newcommand{\\Heldout${k}${tag}}{${v}}\n`
  console.log(slug, JSON.stringify(m))
}
writeFileSync(a.tex, tex)
