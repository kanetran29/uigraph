/**
 * Links the runtime route oracle to the final graph. The probe read each application's live route
 * configuration once (results/<slug>.probe.json, 29-30 October), against a graph whose extractor
 * commit was not recorded; compare-probe.mjs is re-run on that same reading against the final
 * corpus graphs (results-final/). This checks, per application, that the final graph has the same
 * node count and claims exactly the same addresses the framework does not mount, and misses exactly
 * the same ones, so the node-set figures hold for the graph the thesis reports.
 *
 * Usage: node final-check.mjs [--before results] [--final results-final] --tex <out.tex>
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

/** True when two address lists hold the same addresses, in any order. */
export const sameSet = (a, b) => JSON.stringify([...a].sort()) === JSON.stringify([...b].sort())

/** Compares one application's comparison file before and after: equal node counts and address sets. */
export function compareApp(before, final) {
  return {
    nodes: final.counts.extractorNodes,
    invented: final.invented.length,
    missed: final.missed.length,
    same: before.counts.extractorNodes === final.counts.extractorNodes && sameSet(before.invented, final.invented) && sameSet(before.missed, final.missed),
  }
}

/** Reads both directories, compares every application, and writes the macros. */
function main() {
  const a = { before: 'results', final: 'results-final' }
  for (let i = 2; i < process.argv.length; i += 2) a[process.argv[i].replace(/^--/, '')] = process.argv[i + 1]
  const slugs = readdirSync(a.final).filter((f) => f.endsWith('.cmp.json')).map((f) => f.replace('.cmp.json', '')).sort()
  const read = (d, s) => JSON.parse(readFileSync(join(d, `${s}.cmp.json`), 'utf8'))
  const rows = slugs.map((s) => ({ slug: s, ...compareApp(read(a.before, s), read(a.final, s)) }))
  const sum = (k) => rows.reduce((x, r) => x + r[k], 0)
  const m = { ProbeFinalApps: rows.length, ProbeFinalSame: rows.filter((r) => r.same).length, ProbeFinalNodes: sum('nodes'), ProbeFinalInvented: sum('invented'), ProbeFinalMissed: sum('missed') }
  let tex = '% Generated by route-probe/final-check.mjs from results/ and results-final/. Do not edit.\n'
  for (const [k, v] of Object.entries(m)) tex += `\\newcommand{\\${k}}{${v}}\n`
  writeFileSync(a.tex, tex)
  for (const r of rows) console.log(r.slug.padEnd(12), JSON.stringify(r))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
